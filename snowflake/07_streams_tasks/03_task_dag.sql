/* =============================================================================
   03_task_dag.sql — hourly ELT DAG (see docs/diagrams/08_task_dag.mmd)
   - Root runs hourly; children fire only if their stream has data (WHEN is
     evaluated by cloud services → no warehouse resume for empty runs).
   - Batch id = root task's graph run id, shared by all children.
   - Finalizer always runs → audit + alert on failure.
   Deploy pattern: suspend root → (re)create children → resume via SYSTEM$TASK_DEPENDENTS_ENABLE.
   ============================================================================= */
USE ROLE &{ENV}_SR_TRANSFORM;
USE SCHEMA CV_&{ENV}_CONTROL.ORCHESTRATION;

ALTER TASK IF EXISTS T_ROOT_CV_HOURLY SUSPEND;

CREATE OR REPLACE TASK T_ROOT_CV_HOURLY
  WAREHOUSE = &{ENV}_WH_TRANSFORM
  SCHEDULE = 'USING CRON 5 * * * * UTC'
  ALLOW_OVERLAPPING_EXECUTION = FALSE
  SUSPEND_TASK_AFTER_NUM_FAILURES = 3
  TASK_AUTO_RETRY_ATTEMPTS = 2
  USER_TASK_TIMEOUT_MS = 7200000
  COMMENT = 'Root of hourly ELT DAG'
AS
  SELECT SYSTEM$SET_RETURN_VALUE(SYSTEM$TASK_RUNTIME_INFO('CURRENT_TASK_GRAPH_RUN_GROUP_ID'));

-- ---------------------------------------------------------------- STAGE layer
CREATE OR REPLACE TASK T_STAGE_CLAIM_HEADER
  WAREHOUSE = &{ENV}_WH_TRANSFORM AFTER T_ROOT_CV_HOURLY
  WHEN SYSTEM$STREAM_HAS_DATA('CV_&{ENV}_RAW.CLAIMS.STRM_CLAIM_HEADER_STAGE')
AS CALL SP_MERGE_CLAIM_HEADER(SYSTEM$TASK_RUNTIME_INFO('CURRENT_TASK_GRAPH_RUN_GROUP_ID'));

CREATE OR REPLACE TASK T_STAGE_CLAIM_LINE
  WAREHOUSE = &{ENV}_WH_TRANSFORM AFTER T_STAGE_CLAIM_HEADER
  WHEN SYSTEM$STREAM_HAS_DATA('CV_&{ENV}_RAW.CLAIMS.STRM_CLAIM_LINE_STAGE')
AS CALL SP_STAGE_CLAIM_LINE(SYSTEM$TASK_RUNTIME_INFO('CURRENT_TASK_GRAPH_RUN_GROUP_ID'));

CREATE OR REPLACE TASK T_REPLAY_ORPHANS
  WAREHOUSE = &{ENV}_WH_TRANSFORM AFTER T_STAGE_CLAIM_HEADER
AS CALL SP_REPLAY_ORPHAN_LINES(SYSTEM$TASK_RUNTIME_INFO('CURRENT_TASK_GRAPH_RUN_GROUP_ID'));

CREATE OR REPLACE TASK T_STAGE_MEMBER
  WAREHOUSE = &{ENV}_WH_TRANSFORM AFTER T_ROOT_CV_HOURLY
  WHEN SYSTEM$STREAM_HAS_DATA('CV_&{ENV}_RAW.MEMBERSHIP.STRM_MEMBER_STAGE')
AS CALL SP_STAGE_MEMBER(SYSTEM$TASK_RUNTIME_INFO('CURRENT_TASK_GRAPH_RUN_GROUP_ID'));

CREATE OR REPLACE TASK T_STAGE_ELIGIBILITY
  WAREHOUSE = &{ENV}_WH_TRANSFORM AFTER T_ROOT_CV_HOURLY
  WHEN SYSTEM$STREAM_HAS_DATA('CV_&{ENV}_RAW.MEMBERSHIP.STRM_ELIG_STAGE')
AS CALL SP_STAGE_ELIGIBILITY(SYSTEM$TASK_RUNTIME_INFO('CURRENT_TASK_GRAPH_RUN_GROUP_ID'));

-- ----------------------------------------------------------------- CORE layer
CREATE OR REPLACE TASK T_CORE_DIM_MEMBER
  WAREHOUSE = &{ENV}_WH_TRANSFORM AFTER T_STAGE_MEMBER
  WHEN SYSTEM$STREAM_HAS_DATA('CV_&{ENV}_STAGE.MEMBERSHIP.STRM_STG_MEMBER_CORE')
AS CALL SP_MERGE_DIM_MEMBER(SYSTEM$TASK_RUNTIME_INFO('CURRENT_TASK_GRAPH_RUN_GROUP_ID'));

CREATE OR REPLACE TASK T_CORE_FACT_ELIG_MONTH
  WAREHOUSE = &{ENV}_WH_TRANSFORM AFTER T_STAGE_ELIGIBILITY, T_CORE_DIM_MEMBER
  WHEN SYSTEM$STREAM_HAS_DATA('CV_&{ENV}_STAGE.MEMBERSHIP.STRM_STG_ELIG_CORE')
AS CALL SP_MERGE_FACT_ELIGIBILITY_MONTH(SYSTEM$TASK_RUNTIME_INFO('CURRENT_TASK_GRAPH_RUN_GROUP_ID'));

CREATE OR REPLACE TASK T_CORE_DIM_PROVIDER
  WAREHOUSE = &{ENV}_WH_TRANSFORM AFTER T_ROOT_CV_HOURLY
  WHEN SYSTEM$STREAM_HAS_DATA('CV_&{ENV}_RAW.PROVIDER.STRM_PROVIDER_STAGE')
AS CALL SP_MERGE_DIM_PROVIDER(SYSTEM$TASK_RUNTIME_INFO('CURRENT_TASK_GRAPH_RUN_GROUP_ID'));

-- facts AFTER dims: late-arriving member handled by inferred rows inside the proc
CREATE OR REPLACE TASK T_CORE_FACT_CLAIM_LINE
  WAREHOUSE = &{ENV}_WH_TRANSFORM AFTER T_STAGE_CLAIM_LINE, T_CORE_DIM_MEMBER, T_CORE_DIM_PROVIDER
  WHEN SYSTEM$STREAM_HAS_DATA('CV_&{ENV}_STAGE.CLAIMS.STRM_STG_CLAIM_LINE_CORE')
AS CALL SP_MERGE_FACT_CLAIM_LINE(SYSTEM$TASK_RUNTIME_INFO('CURRENT_TASK_GRAPH_RUN_GROUP_ID'));

-- ----------------------------------------------------------- DQ + publish gate
CREATE OR REPLACE TASK T_DQ_AND_PUBLISH_GATE
  WAREHOUSE = &{ENV}_WH_TRANSFORM AFTER T_CORE_FACT_CLAIM_LINE, T_CORE_FACT_ELIG_MONTH
AS
BEGIN
  LET v_batch VARCHAR := SYSTEM$TASK_RUNTIME_INFO('CURRENT_TASK_GRAPH_RUN_GROUP_ID');
  LET v_bd DATE := DATEADD(day, -1, CONVERT_TIMEZONE('America/New_York', CURRENT_TIMESTAMP())::DATE);
  CALL CV_&{ENV}_CONTROL.DQ.SP_RUN_DQ('CV_&{ENV}_STAGE.CLAIMS.CLAIM_LINE', :v_batch, :v_bd);
  CALL CV_&{ENV}_CONTROL.DQ.SP_RUN_DQ('CV_&{ENV}_STAGE.MEMBERSHIP.ELIGIBILITY_SPAN', :v_batch, :v_bd);
  CALL SP_PUBLISH_GATE(:v_bd);
END;

-- ------------------------------------------------------------------ finalizer
CREATE OR REPLACE TASK T_FINALIZER_AUDIT
  WAREHOUSE = &{ENV}_WH_TRANSFORM
  FINALIZE = T_ROOT_CV_HOURLY
AS
BEGIN
  INSERT INTO CV_&{ENV}_CONTROL.AUDIT.AUDIT_BATCH_LOG (BATCH_ID, STEP_NAME, TARGET_OBJECT, STATUS, ERROR_MESSAGE, TASK_NAME)
  SELECT GRAPH_RUN_GROUP_ID, 'DAG_TASK', NAME, STATE, ERROR_MESSAGE, NAME
  FROM TABLE(CV_&{ENV}_CONTROL.INFORMATION_SCHEMA.TASK_HISTORY(
          SCHEDULED_TIME_RANGE_START => DATEADD(hour, -3, CURRENT_TIMESTAMP()), RESULT_LIMIT => 1000))
  WHERE GRAPH_RUN_GROUP_ID = SYSTEM$TASK_RUNTIME_INFO('CURRENT_TASK_GRAPH_RUN_GROUP_ID')
    AND STATE IN ('SUCCEEDED','FAILED','SKIPPED','CANCELLED');
END;

-- Housekeeping: purge STAGE batches older than 3 days (serverless task, tiny)
CREATE OR REPLACE TASK T_PURGE_STAGE
  USER_TASK_MANAGED_INITIAL_WAREHOUSE_SIZE = 'XSMALL'
  SCHEDULE = 'USING CRON 30 9 * * * UTC'
AS
BEGIN
  DELETE FROM CV_&{ENV}_STAGE.CLAIMS.CLAIM_LINE         WHERE _STAGED_AT < DATEADD(day, -3, CURRENT_TIMESTAMP());
  DELETE FROM CV_&{ENV}_STAGE.MEMBERSHIP.MEMBER          WHERE _STAGED_AT < DATEADD(day, -3, CURRENT_TIMESTAMP());
  DELETE FROM CV_&{ENV}_STAGE.MEMBERSHIP.ELIGIBILITY_SPAN WHERE _STAGED_AT < DATEADD(day, -3, CURRENT_TIMESTAMP());
END;

-- Enable the whole graph (root last)
SELECT SYSTEM$TASK_DEPENDENTS_ENABLE('CV_&{ENV}_CONTROL.ORCHESTRATION.T_ROOT_CV_HOURLY');
ALTER TASK T_PURGE_STAGE RESUME;
