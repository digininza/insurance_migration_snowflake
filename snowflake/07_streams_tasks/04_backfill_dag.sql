CREATE OR REPLACE TASK T_ROOT_BACKFILL
  WAREHOUSE = &{ENV}_WH_BACKFILL
  COMMENT = 'No schedule: ADF runs EXECUTE TASK after each backfill wave lands'
AS
BEGIN
  LET cfg VARIANT := PARSE_JSON(SYSTEM$GET_TASK_GRAPH_CONFIG());
  LET v_from DATE := cfg:from_month::DATE;
  LET v_to   DATE := cfg:to_month::DATE;
  LET v_run  VARCHAR := SYSTEM$TASK_RUNTIME_INFO('CURRENT_TASK_GRAPH_RUN_GROUP_ID');
  CALL SP_BACKFILL_BUILD_FACT_CLAIM_LINE(:v_from, :v_to, :v_run);
END;
