/* =============================================================================
   04_backfill_dag.sql — history build, triggered by ADF (EXECUTE TASK), no schedule.
   Strategy (ZERO_COPY_CLONE_TIME_TRAVEL §3): build history into a CLONE of the
   fact, validate, then atomic SWAP — live readers never see a half-built table.
   History is inserted PRE-SORTED by the cluster key so auto-clustering has
   little work to do afterwards.
   ============================================================================= */
USE ROLE &{ENV}_SR_TRANSFORM;
USE SCHEMA CV_&{ENV}_CONTROL.ORCHESTRATION;

CREATE OR REPLACE PROCEDURE SP_BACKFILL_BUILD_FACT_CLAIM_LINE(P_FROM_MONTH DATE, P_TO_MONTH DATE, P_BATCH_ID VARCHAR)
RETURNS VARIANT
LANGUAGE SQL
EXECUTE AS CALLER          -- USE WAREHOUSE needs caller's rights
AS
$$
DECLARE
  v_rows NUMBER;
BEGIN
  USE WAREHOUSE &{ENV}_WH_BACKFILL;
  CREATE TABLE IF NOT EXISTS CV_&{ENV}_CORE.CLAIMS.FACT_CLAIM_LINE_BF CLONE CV_&{ENV}_CORE.CLAIMS.FACT_CLAIM_LINE;
  ALTER TABLE CV_&{ENV}_CORE.CLAIMS.FACT_CLAIM_LINE_BF SUSPEND RECLUSTER;   -- we insert sorted; recluster later

  INSERT INTO CV_&{ENV}_CORE.CLAIMS.FACT_CLAIM_LINE_BF
        (CLAIM_LINE_SK, CLAIM_ID, LINE_NO, CLAIM_LINE_VERSION, IS_CURRENT_VERSION, ADJUSTMENT_TYPE, CLAIM_TYPE,
         MEMBER_SK, RENDERING_PROVIDER_SK, BILLING_PROVIDER_SK, LOB_SK, LOB_CODE, PRIMARY_DX_CD, PROCEDURE_CD,
         PLACE_OF_SERVICE_CD, REVENUE_CD, SERVICE_FROM_DATE_SK, SERVICE_MONTH, RECEIVED_DATE_SK, PAID_DATE_SK, PAID_MONTH,
         LINE_STATUS, DENIAL_REASON_CD, IS_AUTO_ADJUDICATED, UNITS, BILLED_AMT, ALLOWED_AMT, PAID_AMT,
         MEMBER_LIABILITY_AMT, SOURCE_ROWVERSION, _BATCH_ID)
  WITH l AS (
      SELECT * FROM CV_&{ENV}_RAW.CLAIMS.CLAIM_LINE
      WHERE SERVICE_FROM_DT >= :P_FROM_MONTH AND SERVICE_FROM_DT < DATEADD(month, 1, :P_TO_MONTH)
        AND _FILE_NAME LIKE 'backfill/%'
      QUALIFY ROW_NUMBER() OVER (PARTITION BY CLAIM_ID, LINE_NO, CLAIM_LINE_VERSION ORDER BY SOURCE_ROWVERSION DESC) = 1
  ), h AS (
      SELECT * FROM CV_&{ENV}_RAW.CLAIMS.CLAIM_HEADER
      QUALIFY ROW_NUMBER() OVER (PARTITION BY CLAIM_ID ORDER BY SOURCE_ROWVERSION DESC) = 1
  )
  SELECT CV_&{ENV}_CORE.COMMON.SEQ_CLAIM_LINE_SK.NEXTVAL, l.CLAIM_ID, l.LINE_NO, l.CLAIM_LINE_VERSION,
         l.CLAIM_LINE_VERSION = MAX(l.CLAIM_LINE_VERSION) OVER (PARTITION BY l.CLAIM_ID, l.LINE_NO),
         COALESCE(l.ADJUSTMENT_TYPE,'OR'), h.CLAIM_TYPE,
         COALESCE(m.MEMBER_SK,-1), COALESCE(rp.PROVIDER_SK,-1), COALESCE(bp.PROVIDER_SK,-1), COALESCE(lb.LOB_SK,-1), h.LOB_CODE,
         REPLACE(UPPER(l.PRIMARY_DX_CD),'.',''), UPPER(l.PROCEDURE_CD), l.PLACE_OF_SERVICE_CD, l.REVENUE_CD,
         TO_NUMBER(TO_CHAR(l.SERVICE_FROM_DT,'YYYYMMDD')), DATE_TRUNC('month', l.SERVICE_FROM_DT),
         TO_NUMBER(TO_CHAR(h.RECEIVED_DT,'YYYYMMDD')), TO_NUMBER(TO_CHAR(h.PAID_DT,'YYYYMMDD')), DATE_TRUNC('month', h.PAID_DT),
         UPPER(l.LINE_STATUS), l.DENIAL_REASON_CD, l.AUTO_ADJUDICATED_FLG = 'Y', l.UNITS,
         IFF(l.ADJUSTMENT_TYPE='RV', -ABS(l.BILLED_AMT),  l.BILLED_AMT),
         IFF(l.ADJUSTMENT_TYPE='RV', -ABS(l.ALLOWED_AMT), l.ALLOWED_AMT),
         IFF(l.ADJUSTMENT_TYPE='RV', -ABS(l.PAID_AMT),    l.PAID_AMT),
         ROUND(COALESCE(l.COPAY_AMT,0)+COALESCE(l.COINSURANCE_AMT,0)+COALESCE(l.DEDUCTIBLE_AMT,0),2) * IFF(l.ADJUSTMENT_TYPE='RV',-1,1),
         l.SOURCE_ROWVERSION, :P_BATCH_ID
  FROM l
  JOIN h ON h.CLAIM_ID = l.CLAIM_ID
  LEFT JOIN CV_&{ENV}_CORE.MEMBER.DIM_MEMBER m      ON m.MEMBER_ID = h.MEMBER_ID AND m.IS_CURRENT
  LEFT JOIN CV_&{ENV}_CORE.PROVIDER.DIM_PROVIDER rp ON rp.PROVIDER_NPI = l.RENDERING_PROVIDER_NPI AND rp.IS_CURRENT
  LEFT JOIN CV_&{ENV}_CORE.PROVIDER.DIM_PROVIDER bp ON bp.PROVIDER_NPI = h.BILLING_PROVIDER_NPI AND bp.IS_CURRENT
  LEFT JOIN CV_&{ENV}_CORE.COMMON.DIM_LOB lb        ON lb.LOB_CODE = h.LOB_CODE
  ORDER BY DATE_TRUNC('month', l.SERVICE_FROM_DT), h.LOB_CODE;      -- pre-sorted by cluster key
  v_rows := SQLROWCOUNT;

  CALL CV_&{ENV}_CONTROL.AUDIT.SP_LOG_BATCH(:P_BATCH_ID, 'SP_BACKFILL_BUILD_FACT_CLAIM_LINE',
       'CV_&{ENV}_CORE.CLAIMS.FACT_CLAIM_LINE_BF', 'SUCCESS', :v_rows, 0, 0, NULL);
  RETURN OBJECT_CONSTRUCT('rows', v_rows, 'from', P_FROM_MONTH, 'to', P_TO_MONTH);
END;
$$;

