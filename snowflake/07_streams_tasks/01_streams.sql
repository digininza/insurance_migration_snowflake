/* =============================================================================
   01_streams.sql — one stream per (source table, consumer)
   RAW → STAGE: APPEND_ONLY (RAW is insert-only: cheaper, no delete tracking)
   STAGE → CORE: APPEND_ONLY on STAGE (append-only batches)
   Consuming a stream advances its offset for everyone reading THAT stream,
   hence separate streams per consumer (e.g. audit consumer below).
   ============================================================================= */
USE ROLE &{ENV}_SR_CICD;

-- guard against staleness: streams extend retention up to this many days if unconsumed
ALTER DATABASE CV_&{ENV}_RAW   SET MAX_DATA_EXTENSION_TIME_IN_DAYS = 14;
ALTER DATABASE CV_&{ENV}_STAGE SET MAX_DATA_EXTENSION_TIME_IN_DAYS = 14;

CREATE STREAM IF NOT EXISTS CV_&{ENV}_RAW.CLAIMS.STRM_CLAIM_HEADER_STAGE
  ON TABLE CV_&{ENV}_RAW.CLAIMS.CLAIM_HEADER APPEND_ONLY = TRUE COMMENT = 'consumer: SP_MERGE_CLAIM_HEADER';
CREATE STREAM IF NOT EXISTS CV_&{ENV}_RAW.CLAIMS.STRM_CLAIM_LINE_STAGE
  ON TABLE CV_&{ENV}_RAW.CLAIMS.CLAIM_LINE   APPEND_ONLY = TRUE COMMENT = 'consumer: SP_STAGE_CLAIM_LINE';
CREATE STREAM IF NOT EXISTS CV_&{ENV}_RAW.CLAIMS.STRM_CLAIM_LINE_AUDIT
  ON TABLE CV_&{ENV}_RAW.CLAIMS.CLAIM_LINE   APPEND_ONLY = TRUE COMMENT = 'consumer: SP_FEED_STATUS_LOADED (row counts per file)';
CREATE STREAM IF NOT EXISTS CV_&{ENV}_RAW.MEMBERSHIP.STRM_MEMBER_STAGE
  ON TABLE CV_&{ENV}_RAW.MEMBERSHIP.MEMBER   APPEND_ONLY = TRUE COMMENT = 'consumer: SP_STAGE_MEMBER';
CREATE STREAM IF NOT EXISTS CV_&{ENV}_RAW.MEMBERSHIP.STRM_ELIG_STAGE
  ON TABLE CV_&{ENV}_RAW.MEMBERSHIP.ELIGIBILITY_SPAN APPEND_ONLY = TRUE COMMENT = 'consumer: SP_STAGE_ELIGIBILITY';
CREATE STREAM IF NOT EXISTS CV_&{ENV}_RAW.PROVIDER.STRM_PROVIDER_STAGE
  ON TABLE CV_&{ENV}_RAW.PROVIDER.PROVIDER   APPEND_ONLY = TRUE COMMENT = 'consumer: SP_MERGE_DIM_PROVIDER';

CREATE STREAM IF NOT EXISTS CV_&{ENV}_STAGE.CLAIMS.STRM_STG_CLAIM_LINE_CORE
  ON TABLE CV_&{ENV}_STAGE.CLAIMS.CLAIM_LINE APPEND_ONLY = TRUE COMMENT = 'consumer: SP_MERGE_FACT_CLAIM_LINE';
CREATE STREAM IF NOT EXISTS CV_&{ENV}_STAGE.MEMBERSHIP.STRM_STG_MEMBER_CORE
  ON TABLE CV_&{ENV}_STAGE.MEMBERSHIP.MEMBER APPEND_ONLY = TRUE COMMENT = 'consumer: SP_MERGE_DIM_MEMBER';
CREATE STREAM IF NOT EXISTS CV_&{ENV}_STAGE.MEMBERSHIP.STRM_STG_ELIG_CORE
  ON TABLE CV_&{ENV}_STAGE.MEMBERSHIP.ELIGIBILITY_SPAN APPEND_ONLY = TRUE COMMENT = 'consumer: SP_MERGE_FACT_ELIGIBILITY_MONTH';
