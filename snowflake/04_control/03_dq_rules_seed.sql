/* =============================================================================
   03_dq_rules_seed.sql — DQ rules; LEGACY_REF traces each to the Informatica
   transformation it replaced (so recon L5 can prove parity).
   RULE_SQL must return a single number = violating rows.
   ============================================================================= */
USE ROLE &{ENV}_SR_CICD;

MERGE INTO CV_&{ENV}_CONTROL.DQ.DQ_RULE t
USING (SELECT * FROM VALUES
 ('DQ-CLM-001','CV_&{ENV}_STAGE.CLAIMS.CLAIM_LINE','COMPLETENESS',
  'SELECT COUNT(*) FROM CV_&{ENV}_STAGE.CLAIMS.CLAIM_LINE WHERE CLAIM_ID IS NULL OR LINE_NO IS NULL','CRITICAL',
  'm_CLM_CLAIM_LINE_LOAD.RTR_VALID.ERROR group'),
 ('DQ-CLM-002','CV_&{ENV}_STAGE.CLAIMS.CLAIM_LINE','UNIQUENESS',
  'SELECT COUNT(*) FROM (SELECT _BATCH_ID, CLAIM_ID, LINE_NO, CLAIM_LINE_VERSION FROM CV_&{ENV}_STAGE.CLAIMS.CLAIM_LINE GROUP BY 1,2,3,4 HAVING COUNT(*)>1)','CRITICAL',
  'm_CLM_CLAIM_LINE_LOAD.target PK'),
 ('DQ-CLM-003','CV_&{ENV}_STAGE.CLAIMS.CLAIM_LINE','BUSINESS',
  'SELECT COUNT(*) FROM CV_&{ENV}_STAGE.CLAIMS.CLAIM_LINE WHERE ADJUSTMENT_TYPE = ''RV'' AND PAID_AMT > 0','CRITICAL',
  'CLM-R-017 reversal lines carry negative paid (EXP_DERIVE.o_PAID_AMT)'),
 ('DQ-CLM-004','CV_&{ENV}_STAGE.CLAIMS.CLAIM_LINE','VALIDITY',
  'SELECT COUNT(*) FROM CV_&{ENV}_STAGE.CLAIMS.CLAIM_LINE WHERE SERVICE_FROM_DT > SERVICE_TO_DT OR SERVICE_FROM_DT > CURRENT_DATE()','WARN',
  'EXP_DERIVE.v_DATE_CHECK'),
 ('DQ-CLM-005','CV_&{ENV}_STAGE.CLAIMS.CLAIM_LINE','BUSINESS',
  'SELECT COUNT(*) FROM CV_&{ENV}_STAGE.CLAIMS.CLAIM_LINE WHERE ADJUSTMENT_TYPE <> ''RV'' AND PAID_AMT > ALLOWED_AMT','WARN',
  'CLM-R-021 paid cannot exceed allowed'),
 ('DQ-CLM-006','CV_&{ENV}_STAGE.CLAIMS.CLAIM_LINE','REFERENTIAL',
  'SELECT COUNT(*) FROM CV_&{ENV}_STAGE.CLAIMS.CLAIM_LINE s WHERE NOT EXISTS (SELECT 1 FROM CV_&{ENV}_CORE.MEMBER.DIM_MEMBER d WHERE d.MEMBER_ID = s.MEMBER_ID)','WARN',
  'LKP_MEMBER_SK default -1 (late-arriving member → inferred row)'),
 ('DQ-MBR-001','CV_&{ENV}_STAGE.MEMBERSHIP.MEMBER','VALIDITY',
  'SELECT COUNT(*) FROM CV_&{ENV}_STAGE.MEMBERSHIP.MEMBER WHERE BIRTH_DT > CURRENT_DATE() OR BIRTH_DT < ''1900-01-01''','WARN',
  'm_MBR_MEMBER_SCD2.EXP_CLEAN'),
 ('DQ-ELG-004','CV_&{ENV}_STAGE.MEMBERSHIP.ELIGIBILITY_SPAN','BUSINESS',
  'SELECT COUNT(*) FROM CV_&{ENV}_STAGE.MEMBERSHIP.ELIGIBILITY_SPAN a JOIN CV_&{ENV}_STAGE.MEMBERSHIP.ELIGIBILITY_SPAN b ON a.MEMBER_ID=b.MEMBER_ID AND a.LOB_CODE=b.LOB_CODE AND a.ELIG_SPAN_ID<b.ELIG_SPAN_ID AND a.EFFECTIVE_DT<=COALESCE(b.TERM_DT,''9999-12-31'') AND b.EFFECTIVE_DT<=COALESCE(a.TERM_DT,''9999-12-31'')','CRITICAL',
  'ELG-R-004 one active span per member per LOB per day')
 AS s(RULE_ID, TARGET_TABLE, RULE_TYPE, RULE_SQL, SEVERITY, LEGACY_REF)) s
ON t.RULE_ID = s.RULE_ID
WHEN MATCHED THEN UPDATE SET TARGET_TABLE=s.TARGET_TABLE, RULE_TYPE=s.RULE_TYPE, RULE_SQL=s.RULE_SQL, SEVERITY=s.SEVERITY, LEGACY_REF=s.LEGACY_REF
WHEN NOT MATCHED THEN INSERT (RULE_ID, TARGET_TABLE, RULE_TYPE, RULE_SQL, SEVERITY, LEGACY_REF)
                      VALUES (s.RULE_ID, s.TARGET_TABLE, s.RULE_TYPE, s.RULE_SQL, s.SEVERITY, s.LEGACY_REF);
