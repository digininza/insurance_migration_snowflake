/* =============================================================================
   01_control_tables.sql — Snowflake-side control plane
   (ADF's own metadata lives in Azure SQL `ctl` schema — see metadata/ and LLD_ADF.md;
    ADF pushes its per-object run log here at the end of each run.)
   ============================================================================= */
USE ROLE &{ENV}_SR_CICD;

CREATE TABLE IF NOT EXISTS CV_&{ENV}_CONTROL.CONTROL.CTL_FEED (
    FEED_CODE        VARCHAR(40) PRIMARY KEY,   -- e.g. CLAIMS_CLAIM_LINE
    SOURCE_SYSTEM    VARCHAR(20),
    RAW_TABLE        VARCHAR(200),
    CRITICALITY      VARCHAR(12),               -- CRITICAL blocks publish; NON_CRITICAL alerts only
    EXPECTED_BY_UTC  TIME,                      -- SLA for arrival
    LOAD_METHOD      VARCHAR(12),               -- SNOWPIPE | COPY | TASK_COPY
    IS_ACTIVE        BOOLEAN DEFAULT TRUE
) COMMENT = 'Feed registry: criticality drives the publish gate';

CREATE TABLE IF NOT EXISTS CV_&{ENV}_CONTROL.CONTROL.CTL_FEED_STATUS (
    BUSINESS_DATE    DATE,
    FEED_CODE        VARCHAR(40),
    STATUS           VARCHAR(12),               -- EXPECTED | EXTRACTED | LOADED | FAILED | LATE
    ADF_RUN_ID       VARCHAR(64),
    ROWS_EXTRACTED   NUMBER,
    ROWS_LOADED      NUMBER,
    FILES_LOADED     NUMBER,
    UPDATED_AT       TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_FEED_STATUS PRIMARY KEY (BUSINESS_DATE, FEED_CODE)
) COMMENT = 'Per business date feed status: ADF writes EXTRACTED, tasks write LOADED';

CREATE TABLE IF NOT EXISTS CV_&{ENV}_CONTROL.CONTROL.CTL_PUBLISH_STATUS (
    BUSINESS_DATE DATE PRIMARY KEY,
    GATE_STATUS   VARCHAR(10),                  -- PASSED | BLOCKED
    BLOCK_REASONS ARRAY,
    EVALUATED_AT  TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS CV_&{ENV}_CONTROL.CONTROL.CTL_FILE_LOAD_LOG (
    BATCH_ID      VARCHAR(64),
    LOAD_PATH     VARCHAR(12),                  -- BACKFILL | INCREMENTAL | REPLAY
    TARGET_TABLE  VARCHAR(200),
    FILE_NAME     VARCHAR(1000),
    STATUS        VARCHAR(20),
    ROWS_PARSED   NUMBER,
    ROWS_LOADED   NUMBER,
    ERRORS_SEEN   NUMBER,
    FIRST_ERROR   VARCHAR,
    LOAD_METHOD   VARCHAR(10),
    QUERY_ID      VARCHAR(64),
    LOGGED_AT     TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS CV_&{ENV}_CONTROL.CONTROL.CTL_ADF_RUN_LOG (
    ADF_RUN_ID     VARCHAR(64),
    PIPELINE_NAME  VARCHAR(200),
    OBJECT_ID      NUMBER,
    SOURCE_OBJECT  VARCHAR(200),
    BUSINESS_DATE  DATE,
    OLD_WATERMARK  VARCHAR(40),
    NEW_WATERMARK  VARCHAR(40),
    ROWS_READ      NUMBER,
    ROWS_WRITTEN   NUMBER,
    FILES_WRITTEN  NUMBER,
    BYTES_WRITTEN  NUMBER,
    STATUS         VARCHAR(12),
    ERROR_MESSAGE  VARCHAR,
    START_TS       TIMESTAMP_NTZ,
    END_TS         TIMESTAMP_NTZ
) COMMENT = 'Mirror of Azure SQL ctl.pipeline_run pushed by ADF (single audit view in Snowflake)';

CREATE TABLE IF NOT EXISTS CV_&{ENV}_CONTROL.AUDIT.AUDIT_BATCH_LOG (
    AUDIT_ID       NUMBER AUTOINCREMENT,
    BATCH_ID       VARCHAR(64),
    STEP_NAME      VARCHAR(100),
    TARGET_OBJECT  VARCHAR(200),
    STATUS         VARCHAR(10),
    ROWS_INSERTED  NUMBER,
    ROWS_UPDATED   NUMBER,
    ROWS_REJECTED  NUMBER,
    ERROR_MESSAGE  VARCHAR,
    QUERY_ID       VARCHAR(64),
    TASK_NAME      VARCHAR(200),
    LOGGED_BY      VARCHAR(100) DEFAULT CURRENT_ROLE(),
    LOGGED_AT      TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS CV_&{ENV}_CONTROL.DQ.DQ_RULE (
    RULE_ID        VARCHAR(20) PRIMARY KEY,
    TARGET_TABLE   VARCHAR(200),
    RULE_TYPE      VARCHAR(20),     -- COMPLETENESS | VALIDITY | UNIQUENESS | REFERENTIAL | TIMELINESS | BUSINESS
    RULE_SQL       VARCHAR,         -- returns count of violating rows
    SEVERITY       VARCHAR(10),     -- CRITICAL | WARN
    LEGACY_REF     VARCHAR(100),    -- Informatica mapping/transformation the rule came from
    IS_ACTIVE      BOOLEAN DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS CV_&{ENV}_CONTROL.DQ.DQ_RESULT (
    BATCH_ID       VARCHAR(64),
    RULE_ID        VARCHAR(20),
    BUSINESS_DATE  DATE,
    VIOLATIONS     NUMBER,
    STATUS         VARCHAR(6),      -- PASS | FAIL
    EVALUATED_AT   TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS CV_&{ENV}_CONTROL.CONTROL.CUTOVER_CHECKLIST (
    WAVE           VARCHAR(10),
    ITEM_ID        VARCHAR(20),
    DESCRIPTION    VARCHAR(500),
    OWNER          VARCHAR(100),
    STATUS         VARCHAR(12),     -- OPEN | DONE | WAIVED
    EVIDENCE_LINK  VARCHAR(500),
    SIGNED_OFF_BY  VARCHAR(100),
    SIGNED_OFF_AT  TIMESTAMP_LTZ
);

MERGE INTO CV_&{ENV}_CONTROL.CONTROL.CTL_FEED t
USING (SELECT * FROM VALUES
   ('CLAIMS_CLAIM_HEADER',  'CLAIMS',     'CV_&{ENV}_RAW.CLAIMS.CLAIM_HEADER',          'CRITICAL',     '04:30'::TIME, 'SNOWPIPE'),
   ('CLAIMS_CLAIM_LINE',    'CLAIMS',     'CV_&{ENV}_RAW.CLAIMS.CLAIM_LINE',            'CRITICAL',     '04:30'::TIME, 'SNOWPIPE'),
   ('CLAIMS_DIAGNOSIS',     'CLAIMS',     'CV_&{ENV}_RAW.CLAIMS.CLAIM_DIAGNOSIS',       'CRITICAL',     '04:30'::TIME, 'SNOWPIPE'),
   ('MEMBERSHIP_MEMBER',    'MEMBERSHIP', 'CV_&{ENV}_RAW.MEMBERSHIP.MEMBER',            'CRITICAL',     '04:00'::TIME, 'SNOWPIPE'),
   ('MEMBERSHIP_ELIG',      'MEMBERSHIP', 'CV_&{ENV}_RAW.MEMBERSHIP.ELIGIBILITY_SPAN',  'CRITICAL',     '04:00'::TIME, 'SNOWPIPE'),
   ('PROVIDER_PROVIDER',    'PROVIDER',   'CV_&{ENV}_RAW.PROVIDER.PROVIDER',            'CRITICAL',     '04:00'::TIME, 'SNOWPIPE'),
   ('BILLING_INVOICE',      'BILLING',    'CV_&{ENV}_RAW.BILLING.PREMIUM_INVOICE',      'NON_CRITICAL', '05:00'::TIME, 'SNOWPIPE'),
   ('PHARMACY_PBM',         'PBM',        'CV_&{ENV}_RAW.PHARMACY.PBM_CLAIM',           'NON_CRITICAL', '06:00'::TIME, 'SNOWPIPE'),
   ('REFERENCE_ICD10',      'REFERENCE',  'CV_&{ENV}_RAW.REFERENCE.ICD10_CM',           'NON_CRITICAL', NULL,          'TASK_COPY')
   AS s(FEED_CODE, SOURCE_SYSTEM, RAW_TABLE, CRITICALITY, EXPECTED_BY_UTC, LOAD_METHOD)) s
ON t.FEED_CODE = s.FEED_CODE
WHEN MATCHED THEN UPDATE SET SOURCE_SYSTEM = s.SOURCE_SYSTEM, RAW_TABLE = s.RAW_TABLE, CRITICALITY = s.CRITICALITY,
                             EXPECTED_BY_UTC = s.EXPECTED_BY_UTC, LOAD_METHOD = s.LOAD_METHOD
WHEN NOT MATCHED THEN INSERT (FEED_CODE, SOURCE_SYSTEM, RAW_TABLE, CRITICALITY, EXPECTED_BY_UTC, LOAD_METHOD)
                      VALUES (s.FEED_CODE, s.SOURCE_SYSTEM, s.RAW_TABLE, s.CRITICALITY, s.EXPECTED_BY_UTC, s.LOAD_METHOD);
