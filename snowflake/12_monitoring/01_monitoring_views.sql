/* =============================================================================
   01_monitoring_views.sql — operational health + cost views (ACCOUNT_USAGE has
   up to ~45 min latency; INFORMATION_SCHEMA table functions are real-time).
   ============================================================================= */
USE ROLE &{ENV}_SR_CICD;
USE SCHEMA CV_&{ENV}_CONTROL.MONITORING;

CREATE OR REPLACE VIEW V_PIPE_LOADS_24H AS
SELECT PIPE_NAME, TABLE_NAME, COUNT(*) AS FILES, SUM(ROW_COUNT) AS ROWS_LOADED,
       COUNT_IF(STATUS <> 'Loaded') AS FILES_NOT_LOADED, MAX(LAST_LOAD_TIME) AS LAST_LOAD
FROM SNOWFLAKE.ACCOUNT_USAGE.COPY_HISTORY
WHERE LAST_LOAD_TIME > DATEADD(hour, -24, CURRENT_TIMESTAMP()) AND TABLE_CATALOG_NAME = 'CV_&{ENV}_RAW'
GROUP BY 1, 2;

CREATE OR REPLACE VIEW V_TASK_FAILURES_7D AS
SELECT NAME, STATE, ERROR_CODE, ERROR_MESSAGE, SCHEDULED_TIME, COMPLETED_TIME, GRAPH_RUN_GROUP_ID
FROM SNOWFLAKE.ACCOUNT_USAGE.TASK_HISTORY
WHERE DATABASE_NAME = 'CV_&{ENV}_CONTROL' AND STATE = 'FAILED'
  AND SCHEDULED_TIME > DATEADD(day, -7, CURRENT_TIMESTAMP());

CREATE OR REPLACE VIEW V_DT_REFRESH_HEALTH AS
SELECT NAME, SCHEMA_NAME, STATE, REFRESH_ACTION, REFRESH_TRIGGER, DATA_TIMESTAMP,
       REFRESH_START_TIME, REFRESH_END_TIME, STATE_MESSAGE
FROM SNOWFLAKE.ACCOUNT_USAGE.DYNAMIC_TABLE_REFRESH_HISTORY
WHERE DATABASE_NAME = 'CV_&{ENV}_MART' AND REFRESH_START_TIME > DATEADD(day, -2, CURRENT_TIMESTAMP());

CREATE OR REPLACE VIEW V_WAREHOUSE_CREDITS_30D AS
SELECT WAREHOUSE_NAME, DATE_TRUNC('day', START_TIME) AS DAY, SUM(CREDITS_USED) AS CREDITS
FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
WHERE START_TIME > DATEADD(day, -30, CURRENT_TIMESTAMP()) AND WAREHOUSE_NAME LIKE '&{ENV}_WH_%'
GROUP BY 1, 2;

CREATE OR REPLACE VIEW V_SERVERLESS_CREDITS_30D AS
SELECT 'SNOWPIPE' AS SERVICE, DATE_TRUNC('day', START_TIME) AS DAY, SUM(CREDITS_USED) AS CREDITS
FROM SNOWFLAKE.ACCOUNT_USAGE.PIPE_USAGE_HISTORY WHERE START_TIME > DATEADD(day, -30, CURRENT_TIMESTAMP()) GROUP BY 1, 2
UNION ALL
SELECT 'AUTO_CLUSTERING', DATE_TRUNC('day', START_TIME), SUM(CREDITS_USED)
FROM SNOWFLAKE.ACCOUNT_USAGE.AUTOMATIC_CLUSTERING_HISTORY WHERE START_TIME > DATEADD(day, -30, CURRENT_TIMESTAMP()) GROUP BY 1, 2
UNION ALL
SELECT 'SEARCH_OPTIMIZATION', DATE_TRUNC('day', START_TIME), SUM(CREDITS_USED)
FROM SNOWFLAKE.ACCOUNT_USAGE.SEARCH_OPTIMIZATION_HISTORY WHERE START_TIME > DATEADD(day, -30, CURRENT_TIMESTAMP()) GROUP BY 1, 2
UNION ALL
SELECT 'SERVERLESS_TASKS', DATE_TRUNC('day', START_TIME), SUM(CREDITS_USED)
FROM SNOWFLAKE.ACCOUNT_USAGE.SERVERLESS_TASK_HISTORY WHERE START_TIME > DATEADD(day, -30, CURRENT_TIMESTAMP()) GROUP BY 1, 2;

-- Pruning health on the big fact: queries scanning > 50% of partitions
CREATE OR REPLACE VIEW V_POOR_PRUNING_FACT_CLAIM AS
SELECT QUERY_ID, USER_NAME, WAREHOUSE_NAME, PARTITIONS_SCANNED, PARTITIONS_TOTAL,
       ROUND(PARTITIONS_SCANNED / NULLIF(PARTITIONS_TOTAL, 0), 3) AS SCAN_RATIO,
       BYTES_SPILLED_TO_LOCAL_STORAGE, BYTES_SPILLED_TO_REMOTE_STORAGE, TOTAL_ELAPSED_TIME / 1000 AS SECONDS
FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
WHERE START_TIME > DATEADD(day, -1, CURRENT_TIMESTAMP())
  AND QUERY_TEXT ILIKE '%FACT_CLAIM_LINE%' AND PARTITIONS_TOTAL > 1000
  AND PARTITIONS_SCANNED / NULLIF(PARTITIONS_TOTAL, 0) > 0.5;

-- SLA: was the publish gate PASSED by 05:30 ET?
CREATE OR REPLACE VIEW V_DAILY_SLA AS
SELECT BUSINESS_DATE, GATE_STATUS, CONVERT_TIMEZONE('America/New_York', EVALUATED_AT) AS EVALUATED_ET,
       IFF(GATE_STATUS = 'PASSED'
           AND CONVERT_TIMEZONE('America/New_York', EVALUATED_AT)::TIME <= '05:30'::TIME, 'MET', 'MISSED') AS SLA
FROM CV_&{ENV}_CONTROL.CONTROL.CTL_PUBLISH_STATUS;

-- Compat-view usage (sunset decisions)
CREATE OR REPLACE VIEW V_LEGACY_COMPAT_USAGE_90D AS
SELECT f.value:"objectName"::VARCHAR AS OBJECT_NAME, COUNT(DISTINCT ah.QUERY_ID) AS QUERIES,
       COUNT(DISTINCT ah.USER_NAME) AS USERS, MAX(ah.QUERY_START_TIME) AS LAST_READ
FROM SNOWFLAKE.ACCOUNT_USAGE.ACCESS_HISTORY ah, LATERAL FLATTEN(ah.DIRECT_OBJECTS_ACCESSED) f
WHERE ah.QUERY_START_TIME > DATEADD(day, -90, CURRENT_TIMESTAMP())
  AND f.value:"objectName"::VARCHAR ILIKE 'CV_&{ENV}_MART.LEGACY_COMPAT.%'
GROUP BY 1;
