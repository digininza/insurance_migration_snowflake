/* =============================================================================
   01_stage_tables.sql — STAGE = typed, cleansed, deduped per batch, append-only
   with _BATCH_ID. A stream on each STAGE table feeds CORE, so a CORE failure
   never loses a batch (the stream simply holds it until the next run).
   Purged after 3 days by T_PURGE_STAGE.
   ============================================================================= */
USE ROLE &{ENV}_SR_CICD;

CREATE TRANSIENT TABLE IF NOT EXISTS CV_&{ENV}_STAGE.CLAIMS.CLAIM_LINE (
    _BATCH_ID              VARCHAR(64),
    CLAIM_ID               VARCHAR(20)   NOT NULL,
    LINE_NO                NUMBER(4,0)   NOT NULL,
    CLAIM_LINE_VERSION     NUMBER(4,0)   NOT NULL,
    ADJUSTMENT_TYPE        VARCHAR(2),
    CLAIM_TYPE             VARCHAR(2),
    MEMBER_ID              VARCHAR(20),
    LOB_CODE               VARCHAR(4),
    BILLING_PROVIDER_NPI   VARCHAR(10),
    RENDERING_PROVIDER_NPI VARCHAR(10),
    RECEIVED_DT            DATE,
    PAID_DT                DATE,
    SERVICE_FROM_DT        DATE,
    SERVICE_TO_DT          DATE,
    SERVICE_MONTH          DATE,          -- DATE_TRUNC('month', service_from_dt): cluster key downstream
    PROCEDURE_CD           VARCHAR(7),
    PROCEDURE_MODIFIER     VARCHAR(2),
    REVENUE_CD             VARCHAR(4),
    PLACE_OF_SERVICE_CD    VARCHAR(2),
    PRIMARY_DX_CD          VARCHAR(8),
    UNITS                  NUMBER(9,2),
    BILLED_AMT             NUMBER(18,2),
    ALLOWED_AMT            NUMBER(18,2),
    PAID_AMT               NUMBER(18,2),
    MEMBER_LIABILITY_AMT   NUMBER(18,2),
    LINE_STATUS            VARCHAR(10),
    DENIAL_REASON_CD       VARCHAR(10),
    IS_AUTO_ADJUDICATED    BOOLEAN,
    SOURCE_ROWVERSION      NUMBER(20,0),
    SOURCE_UPDATED_TS      TIMESTAMP_NTZ,
    _FILE_NAME             VARCHAR,
    _STAGED_AT             TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
) COMMENT = 'Grain: claim_id × line_no × version, deduped within batch';

CREATE TRANSIENT TABLE IF NOT EXISTS CV_&{ENV}_STAGE.MEMBERSHIP.MEMBER (
    _BATCH_ID VARCHAR(64), MEMBER_ID VARCHAR(20) NOT NULL, SUBSCRIBER_ID VARCHAR(20), RELATIONSHIP_CD VARCHAR(2),
    FIRST_NAME VARCHAR(60), LAST_NAME VARCHAR(60), MIDDLE_NAME VARCHAR(60), BIRTH_DT DATE, GENDER_CD VARCHAR(1),
    SSN VARCHAR(11), ADDRESS_LINE1 VARCHAR(100), CITY VARCHAR(60), STATE_CD VARCHAR(2), ZIP5 VARCHAR(5),
    PHONE VARCHAR(20), EMAIL VARCHAR(120), GROUP_ID VARCHAR(20), LOB_CODE VARCHAR(4), PCP_NPI VARCHAR(10),
    IS_ACTIVE BOOLEAN, SOURCE_UPDATED_TS TIMESTAMP_NTZ, ROW_HASH VARCHAR(64),
    _STAGED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
) COMMENT = 'Grain: member, latest version within batch. PHI.';

CREATE TRANSIENT TABLE IF NOT EXISTS CV_&{ENV}_STAGE.MEMBERSHIP.ELIGIBILITY_SPAN (
    _BATCH_ID VARCHAR(64), ELIG_SPAN_ID NUMBER(18,0) NOT NULL, MEMBER_ID VARCHAR(20), PLAN_ID VARCHAR(12),
    LOB_CODE VARCHAR(4), EFFECTIVE_DT DATE, TERM_DT DATE, COVERAGE_TIER VARCHAR(4), IS_VOID BOOLEAN,
    SOURCE_UPDATED_TS TIMESTAMP_NTZ, _STAGED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TRANSIENT TABLE IF NOT EXISTS CV_&{ENV}_STAGE.QUARANTINE.CLAIM_LINE_REJECT (
    _BATCH_ID VARCHAR(64), REJECT_REASON VARCHAR(200), RECORD VARIANT, _FILE_NAME VARCHAR,
    _REJECTED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
) DATA_RETENTION_TIME_IN_DAYS = 1
  COMMENT = 'Replaces Informatica RTR_VALID error group → EDW.CLAIM_LINE_ERR / .bad files';

CREATE TRANSIENT TABLE IF NOT EXISTS CV_&{ENV}_STAGE.QUARANTINE.MEMBER_REJECT (
    _BATCH_ID VARCHAR(64), REJECT_REASON VARCHAR(200), RECORD VARIANT,
    _REJECTED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);
