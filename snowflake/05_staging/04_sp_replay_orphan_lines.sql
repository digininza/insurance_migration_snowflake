/* =============================================================================
   04_sp_replay_orphan_lines.sql — re-drive quarantined ORPHAN_LINE_NO_HEADER
   rows once their header has arrived. Re-inserting into RAW (with the original
   file lineage) lets the normal stream → stage → core path process them,
   so there is exactly one code path for claim lines.
   Scheduled hourly after T_STAGE_CLAIM_HEADER (see 07_streams_tasks).
   ============================================================================= */
USE ROLE &{ENV}_SR_CICD;

CREATE OR REPLACE PROCEDURE CV_&{ENV}_CONTROL.ORCHESTRATION.SP_REPLAY_ORPHAN_LINES(P_BATCH_ID VARCHAR)
RETURNS NUMBER
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  v_replayed NUMBER DEFAULT 0;
BEGIN
  CREATE OR REPLACE TEMPORARY TABLE TMP_ORPHANS AS      -- DDL: outside the transaction
    SELECT q.RECORD, q._FILE_NAME, q._BATCH_ID
    FROM CV_&{ENV}_STAGE.QUARANTINE.CLAIM_LINE_REJECT q
    JOIN CV_&{ENV}_CORE.CLAIMS.CLAIM_HEADER_CURRENT h ON h.CLAIM_ID = TRIM(q.RECORD:CLAIM_ID::VARCHAR)
    WHERE q.REJECT_REASON = 'ORPHAN_LINE_NO_HEADER';

  BEGIN TRANSACTION;
  INSERT INTO CV_&{ENV}_RAW.CLAIMS.CLAIM_LINE
  SELECT r.RECORD:CLAIM_ID::VARCHAR, r.RECORD:LINE_NO::NUMBER, r.RECORD:CLAIM_LINE_VERSION::NUMBER,
         r.RECORD:ADJUSTMENT_TYPE::VARCHAR, r.RECORD:RENDERING_PROVIDER_NPI::VARCHAR,
         r.RECORD:SERVICE_FROM_DT::DATE, r.RECORD:SERVICE_TO_DT::DATE, r.RECORD:PROCEDURE_CD::VARCHAR,
         r.RECORD:PROCEDURE_MODIFIER::VARCHAR, r.RECORD:REVENUE_CD::VARCHAR, r.RECORD:PLACE_OF_SERVICE_CD::VARCHAR,
         r.RECORD:PRIMARY_DX_CD::VARCHAR, r.RECORD:UNITS::NUMBER(9,2),
         r.RECORD:BILLED_AMT::NUMBER(18,2), r.RECORD:ALLOWED_AMT::NUMBER(18,2), r.RECORD:PAID_AMT::NUMBER(18,2),
         r.RECORD:COPAY_AMT::NUMBER(18,2), r.RECORD:COINSURANCE_AMT::NUMBER(18,2), r.RECORD:DEDUCTIBLE_AMT::NUMBER(18,2),
         r.RECORD:LINE_STATUS::VARCHAR, r.RECORD:DENIAL_REASON_CD::VARCHAR, r.RECORD:AUTO_ADJUDICATED_FLG::VARCHAR,
         r.RECORD:SOURCE_ROWVERSION::NUMBER, r.RECORD:UPDATED_TS::TIMESTAMP_NTZ,
         r._FILE_NAME, r.RECORD:_FILE_ROW::NUMBER, r.RECORD:_FILE_LAST_MODIFIED::TIMESTAMP_LTZ, CURRENT_TIMESTAMP()
  FROM TMP_ORPHANS r;
  v_replayed := SQLROWCOUNT;

  DELETE FROM CV_&{ENV}_STAGE.QUARANTINE.CLAIM_LINE_REJECT q
  USING TMP_ORPHANS o
  WHERE q.REJECT_REASON = 'ORPHAN_LINE_NO_HEADER' AND q.RECORD = o.RECORD;
  COMMIT;

  CALL CV_&{ENV}_CONTROL.AUDIT.SP_LOG_BATCH(:P_BATCH_ID, 'SP_REPLAY_ORPHAN_LINES', 'CV_&{ENV}_RAW.CLAIMS.CLAIM_LINE',
                                            'SUCCESS', :v_replayed, 0, 0, NULL);
  RETURN v_replayed;
EXCEPTION
  WHEN OTHER THEN
    ROLLBACK;
    RAISE;
END;
$$;
