/* =============================================================================
   03_sp_stage_member_eligibility.sql
   Replaces m_MBR_MEMBER_SCD2 (EXP_CLEAN part) and m_ELG_SPAN_LOAD.
   Oracle semantics preserved: '' → NULL (NULLIF(TRIM(x),'')) — recon break #1.
   ROW_HASH over SCD2-tracked columns is computed here once.
   ============================================================================= */
USE ROLE &{ENV}_SR_CICD;

CREATE OR REPLACE PROCEDURE CV_&{ENV}_CONTROL.ORCHESTRATION.SP_STAGE_MEMBER(P_BATCH_ID VARCHAR)
RETURNS VARIANT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  v_staged NUMBER DEFAULT 0;
  v_rejected NUMBER DEFAULT 0;
BEGIN
  CREATE OR REPLACE TEMPORARY TABLE TMP_MEMBER_DELTA LIKE CV_&{ENV}_RAW.MEMBERSHIP.MEMBER;
  BEGIN TRANSACTION;
  INSERT INTO TMP_MEMBER_DELTA
    SELECT * EXCLUDE (METADATA$ACTION, METADATA$ISUPDATE, METADATA$ROW_ID)
    FROM CV_&{ENV}_RAW.MEMBERSHIP.STRM_MEMBER_STAGE;

  INSERT INTO CV_&{ENV}_STAGE.MEMBERSHIP.MEMBER
  SELECT :P_BATCH_ID, TRIM(MEMBER_ID), NULLIF(TRIM(SUBSCRIBER_ID),''), NULLIF(TRIM(RELATIONSHIP_CD),''),
         INITCAP(NULLIF(TRIM(FIRST_NAME),'')), INITCAP(NULLIF(TRIM(LAST_NAME),'')), INITCAP(NULLIF(TRIM(MIDDLE_NAME),'')),
         BIRTH_DT, UPPER(NULLIF(TRIM(GENDER_CD),'')),
         NULLIF(REGEXP_REPLACE(SSN, '[^0-9]', ''), ''),
         NULLIF(TRIM(ADDRESS_LINE1),''), INITCAP(NULLIF(TRIM(CITY),'')), UPPER(NULLIF(TRIM(STATE_CD),'')),
         LEFT(REGEXP_REPLACE(ZIP_CD, '[^0-9]', ''), 5),
         NULLIF(REGEXP_REPLACE(PHONE, '[^0-9]', ''), ''), LOWER(NULLIF(TRIM(EMAIL),'')),
         NULLIF(TRIM(GROUP_ID),''), UPPER(TRIM(LOB_CODE)), NULLIF(TRIM(PCP_NPI),''),
         (RECORD_STATUS = 'A'), LAST_UPDATE_TS,
         SHA2(CONCAT_WS('|', COALESCE(TRIM(SUBSCRIBER_ID),''), COALESCE(INITCAP(TRIM(FIRST_NAME)),''),
                        COALESCE(INITCAP(TRIM(LAST_NAME)),''), COALESCE(TO_VARCHAR(BIRTH_DT),''),
                        COALESCE(UPPER(TRIM(GENDER_CD)),''), COALESCE(TRIM(ADDRESS_LINE1),''),
                        COALESCE(LEFT(REGEXP_REPLACE(ZIP_CD,'[^0-9]',''),5),''), COALESCE(TRIM(GROUP_ID),''),
                        COALESCE(UPPER(TRIM(LOB_CODE)),''), COALESCE(TRIM(PCP_NPI),''), COALESCE(RECORD_STATUS,'')), 256),
         CURRENT_TIMESTAMP()
  FROM TMP_MEMBER_DELTA
  WHERE MEMBER_ID IS NOT NULL AND LOB_CODE IN ('COM','MA','MCD')
  QUALIFY ROW_NUMBER() OVER (PARTITION BY TRIM(MEMBER_ID) ORDER BY LAST_UPDATE_TS DESC, _FILE_ROW DESC) = 1;
  v_staged := SQLROWCOUNT;

  INSERT INTO CV_&{ENV}_STAGE.QUARANTINE.MEMBER_REJECT (_BATCH_ID, REJECT_REASON, RECORD)
  SELECT :P_BATCH_ID, IFF(MEMBER_ID IS NULL, 'MISSING_MEMBER_ID', 'UNKNOWN_LOB'), OBJECT_CONSTRUCT_KEEP_NULL(*)
  FROM TMP_MEMBER_DELTA WHERE MEMBER_ID IS NULL OR LOB_CODE IS NULL OR LOB_CODE NOT IN ('COM','MA','MCD');
  v_rejected := SQLROWCOUNT;
  COMMIT;

  CALL CV_&{ENV}_CONTROL.AUDIT.SP_LOG_BATCH(:P_BATCH_ID, 'SP_STAGE_MEMBER', 'CV_&{ENV}_STAGE.MEMBERSHIP.MEMBER',
                                            'SUCCESS', :v_staged, 0, :v_rejected, NULL);
  RETURN OBJECT_CONSTRUCT('staged', v_staged, 'quarantined', v_rejected);
EXCEPTION
  WHEN OTHER THEN
    ROLLBACK;
    CALL CV_&{ENV}_CONTROL.AUDIT.SP_LOG_BATCH(:P_BATCH_ID, 'SP_STAGE_MEMBER', 'CV_&{ENV}_STAGE.MEMBERSHIP.MEMBER',
                                              'FAILED', 0, 0, 0, :SQLERRM);
    RAISE;
END;
$$;

CREATE OR REPLACE PROCEDURE CV_&{ENV}_CONTROL.ORCHESTRATION.SP_STAGE_ELIGIBILITY(P_BATCH_ID VARCHAR)
RETURNS VARIANT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  v_staged NUMBER DEFAULT 0;
BEGIN
  BEGIN TRANSACTION;
  INSERT INTO CV_&{ENV}_STAGE.MEMBERSHIP.ELIGIBILITY_SPAN
  SELECT :P_BATCH_ID, ELIG_SPAN_ID, TRIM(MEMBER_ID), TRIM(PLAN_ID), UPPER(TRIM(LOB_CODE)),
         EFFECTIVE_DT,
         NULLIF(TERM_DT, '9999-12-31'::DATE),      -- legacy open-ended sentinel → NULL
         NULLIF(TRIM(COVERAGE_TIER),''), (VOID_FLG = 'Y'), LAST_UPDATE_TS, CURRENT_TIMESTAMP()
  FROM CV_&{ENV}_RAW.MEMBERSHIP.STRM_ELIG_STAGE
  WHERE ELIG_SPAN_ID IS NOT NULL AND MEMBER_ID IS NOT NULL AND EFFECTIVE_DT IS NOT NULL
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ELIG_SPAN_ID ORDER BY LAST_UPDATE_TS DESC, _FILE_ROW DESC) = 1;
  v_staged := SQLROWCOUNT;
  COMMIT;
  CALL CV_&{ENV}_CONTROL.AUDIT.SP_LOG_BATCH(:P_BATCH_ID, 'SP_STAGE_ELIGIBILITY', 'CV_&{ENV}_STAGE.MEMBERSHIP.ELIGIBILITY_SPAN',
                                            'SUCCESS', :v_staged, 0, 0, NULL);
  RETURN OBJECT_CONSTRUCT('staged', v_staged);
EXCEPTION
  WHEN OTHER THEN
    ROLLBACK;
    CALL CV_&{ENV}_CONTROL.AUDIT.SP_LOG_BATCH(:P_BATCH_ID, 'SP_STAGE_ELIGIBILITY', 'CV_&{ENV}_STAGE.MEMBERSHIP.ELIGIBILITY_SPAN',
                                              'FAILED', 0, 0, 0, :SQLERRM);
    RAISE;
END;
$$;
