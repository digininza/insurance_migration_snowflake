/* =============================================================================
   02_facts.sql — CORE facts
   FACT_CLAIM_LINE: every adjudication version kept; IS_CURRENT_VERSION maintained.
   Clustered by (SERVICE_MONTH, LOB_CODE) — ADR-012. Money = NUMBER(18,2).
   ============================================================================= */
USE ROLE &{ENV}_SR_CICD;

-- Current-state claim header (operational helper for STAGE joins; one row per claim)
CREATE TABLE IF NOT EXISTS CV_&{ENV}_CORE.CLAIMS.CLAIM_HEADER_CURRENT (
    CLAIM_ID VARCHAR(20) PRIMARY KEY, CLAIM_TYPE VARCHAR(2), MEMBER_ID VARCHAR(20), SUBSCRIBER_ID VARCHAR(20),
    BILLING_PROVIDER_NPI VARCHAR(10), RECEIVED_DT DATE, ADJUDICATED_TS TIMESTAMP_NTZ, PAID_DT DATE,
    CLAIM_STATUS VARCHAR(10), LOB_CODE VARCHAR(4), SOURCE_ROWVERSION NUMBER(20,0), _UPDATED_AT TIMESTAMP_LTZ
) COMMENT = 'Grain: claim (latest header version). Search optimization on CLAIM_ID.';

CREATE TABLE IF NOT EXISTS CV_&{ENV}_CORE.CLAIMS.FACT_CLAIM_LINE (
    CLAIM_LINE_SK           NUMBER(18,0) NOT NULL,
    CLAIM_ID                VARCHAR(20)  NOT NULL,
    LINE_NO                 NUMBER(4,0)  NOT NULL,
    CLAIM_LINE_VERSION      NUMBER(4,0)  NOT NULL,
    IS_CURRENT_VERSION      BOOLEAN      NOT NULL,
    ADJUSTMENT_TYPE         VARCHAR(2),
    CLAIM_TYPE              VARCHAR(2),
    MEMBER_SK               NUMBER(18,0) NOT NULL,
    RENDERING_PROVIDER_SK   NUMBER(18,0) NOT NULL,
    BILLING_PROVIDER_SK     NUMBER(18,0) NOT NULL,
    LOB_SK                  NUMBER(4,0)  NOT NULL,
    LOB_CODE                VARCHAR(4),                -- denormalised for clustering + row access
    PRIMARY_DX_CD           VARCHAR(8),
    PROCEDURE_CD            VARCHAR(7),
    PLACE_OF_SERVICE_CD     VARCHAR(2),
    REVENUE_CD              VARCHAR(4),
    SERVICE_FROM_DATE_SK    NUMBER(8,0),
    SERVICE_MONTH           DATE NOT NULL,
    RECEIVED_DATE_SK        NUMBER(8,0),
    PAID_DATE_SK            NUMBER(8,0),
    PAID_MONTH              DATE,
    LINE_STATUS             VARCHAR(10),
    DENIAL_REASON_CD        VARCHAR(10),
    IS_AUTO_ADJUDICATED     BOOLEAN,
    UNITS                   NUMBER(9,2),
    BILLED_AMT              NUMBER(18,2),
    ALLOWED_AMT             NUMBER(18,2),
    PAID_AMT                NUMBER(18,2),
    MEMBER_LIABILITY_AMT    NUMBER(18,2),
    SOURCE_ROWVERSION       NUMBER(20,0),
    _BATCH_ID               VARCHAR(64),
    _INSERTED_AT            TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
    _UPDATED_AT             TIMESTAMP_LTZ,
    CONSTRAINT PK_FACT_CLAIM_LINE PRIMARY KEY (CLAIM_LINE_SK),
    CONSTRAINT UK_FACT_CLAIM_LINE UNIQUE (CLAIM_ID, LINE_NO, CLAIM_LINE_VERSION)   -- informational; enforced by MERGE + DQ
)
CLUSTER BY (SERVICE_MONTH, LOB_CODE)
COMMENT = 'Grain: claim line × adjudication version. ~2.4B rows. Reversals are negative rows.';

ALTER TABLE CV_&{ENV}_CORE.CLAIMS.FACT_CLAIM_LINE     ADD SEARCH OPTIMIZATION ON EQUALITY(CLAIM_ID);
ALTER TABLE CV_&{ENV}_CORE.CLAIMS.CLAIM_HEADER_CURRENT ADD SEARCH OPTIMIZATION ON EQUALITY(CLAIM_ID);

CREATE TABLE IF NOT EXISTS CV_&{ENV}_CORE.CLAIMS.FACT_CLAIM_DIAGNOSIS (
    CLAIM_ID VARCHAR(20) NOT NULL, DX_SEQ NUMBER(2,0) NOT NULL, DX_CD VARCHAR(8), IS_PRIMARY BOOLEAN,
    IS_PRESENT_ON_ADMISSION BOOLEAN, _BATCH_ID VARCHAR(64)
) COMMENT = 'Bridge: claim × diagnosis (legacy Normalizer NRM_DX1_DX12 → rows at source)';

CREATE TABLE IF NOT EXISTS CV_&{ENV}_CORE.MEMBER.ELIGIBILITY_SPAN_CURRENT (
    ELIG_SPAN_ID NUMBER(18,0) PRIMARY KEY, MEMBER_ID VARCHAR(20), PLAN_ID VARCHAR(12), LOB_CODE VARCHAR(4),
    EFFECTIVE_DT DATE, TERM_DT DATE, COVERAGE_TIER VARCHAR(4), IS_VOID BOOLEAN, SOURCE_UPDATED_TS TIMESTAMP_NTZ
) COMMENT = 'Grain: eligibility span (latest). Source of member-month explosion.';

CREATE TABLE IF NOT EXISTS CV_&{ENV}_CORE.MEMBER.FACT_ELIGIBILITY_MONTH (
    MEMBER_SK NUMBER(18,0) NOT NULL, MEMBER_ID VARCHAR(20) NOT NULL, PLAN_ID VARCHAR(12), LOB_CODE VARCHAR(4) NOT NULL,
    ELIGIBILITY_MONTH DATE NOT NULL, COVERAGE_TIER VARCHAR(4),
    MEMBER_MONTH NUMBER(1,0) NOT NULL,     -- 1 if eligible on the 15th (CareVista member-month rule, ELG-R-001)
    ELIG_SPAN_ID NUMBER(18,0), _BATCH_ID VARCHAR(64), _UPDATED_AT TIMESTAMP_LTZ,
    CONSTRAINT PK_FACT_ELIG_MONTH PRIMARY KEY (MEMBER_ID, LOB_CODE, ELIGIBILITY_MONTH)
) CLUSTER BY (ELIGIBILITY_MONTH)
  COMMENT = 'Grain: member × LOB × month (periodic snapshot). Denominator of PMPM.';

CREATE TABLE IF NOT EXISTS CV_&{ENV}_CORE.FINANCE.FACT_PREMIUM_INVOICE (
    INVOICE_ID VARCHAR(20) PRIMARY KEY, GROUP_SK NUMBER(18,0), LOB_CODE VARCHAR(4), BILLING_MONTH DATE,
    SUBSCRIBER_COUNT NUMBER(9,0), MEMBER_COUNT NUMBER(9,0), INVOICE_AMT NUMBER(18,2), DUE_DT DATE,
    INVOICE_STATUS VARCHAR(10), _BATCH_ID VARCHAR(64)
) COMMENT = 'Grain: premium invoice (group × billing month)';

CREATE TABLE IF NOT EXISTS CV_&{ENV}_CORE.FINANCE.FACT_PREMIUM_PAYMENT (
    PAYMENT_ID VARCHAR(20) PRIMARY KEY, INVOICE_ID VARCHAR(20), GROUP_SK NUMBER(18,0), LOB_CODE VARCHAR(4),
    PAYMENT_DT DATE, PAYMENT_AMT NUMBER(18,2), PAYMENT_METHOD VARCHAR(6), _BATCH_ID VARCHAR(64)
);

CREATE TABLE IF NOT EXISTS CV_&{ENV}_CORE.PHARMACY.FACT_PHARMACY_CLAIM (
    RX_CLAIM_ID VARCHAR(24) PRIMARY KEY, MEMBER_SK NUMBER(18,0), PRESCRIBER_SK NUMBER(18,0), LOB_CODE VARCHAR(4),
    NDC VARCHAR(11), FILL_DT DATE, FILL_MONTH DATE, DAYS_SUPPLY NUMBER(4,0), QUANTITY NUMBER(12,3),
    INGREDIENT_COST_AMT NUMBER(18,2), DISPENSING_FEE_AMT NUMBER(18,2), PLAN_PAID_AMT NUMBER(18,2),
    MEMBER_PAID_AMT NUMBER(18,2), CLAIM_STATUS VARCHAR(2), _BATCH_ID VARCHAR(64)
) CLUSTER BY (FILL_MONTH);
