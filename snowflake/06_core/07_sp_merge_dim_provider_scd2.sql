/* =============================================================================
   07_sp_merge_dim_provider_scd2.sql — SCD2 DIM_PROVIDER straight from the RAW stream
   (provider volume is small: stage + merge in one proc). Same UNION ALL
   null-merge-key pattern as DIM_MEMBER; inferred providers upgraded in place.
   ============================================================================= */
USE ROLE &{ENV}_SR_CICD;

CREATE OR REPLACE PROCEDURE CV_&{ENV}_CONTROL.ORCHESTRATION.SP_MERGE_DIM_PROVIDER(P_BATCH_ID VARCHAR)
RETURNS VARIANT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  v_ins NUMBER DEFAULT 0;
  v_upd NUMBER DEFAULT 0;
BEGIN
  CREATE OR REPLACE TEMPORARY TABLE TMP_PROVIDER_SRC (
      PROVIDER_NPI VARCHAR(10), PROVIDER_NAME VARCHAR(200), PROVIDER_TYPE VARCHAR(4), SPECIALTY_CD VARCHAR(6),
      TAXONOMY_CD VARCHAR(10), NETWORK_ID VARCHAR(10), IS_PARTICIPATING BOOLEAN, STATE_CD VARCHAR(2), ZIP5 VARCHAR(5),
      ROW_HASH VARCHAR(64), SOURCE_UPDATED_TS TIMESTAMP_NTZ);

  BEGIN TRANSACTION;
  INSERT INTO TMP_PROVIDER_SRC
  SELECT TRIM(PROVIDER_NPI), NULLIF(TRIM(PROVIDER_NAME),''), NULLIF(TRIM(PROVIDER_TYPE),''), NULLIF(TRIM(SPECIALTY_CD),''),
         NULLIF(TRIM(TAXONOMY_CD),''), NULLIF(TRIM(NETWORK_ID),''), (PAR_STATUS = 'Y'), UPPER(NULLIF(TRIM(STATE_CD),'')),
         LEFT(REGEXP_REPLACE(ZIP_CD,'[^0-9]',''),5),
         SHA2(CONCAT_WS('|', COALESCE(TRIM(PROVIDER_NAME),''), COALESCE(TRIM(PROVIDER_TYPE),''), COALESCE(TRIM(SPECIALTY_CD),''),
                        COALESCE(TRIM(TAXONOMY_CD),''), COALESCE(TRIM(NETWORK_ID),''), COALESCE(PAR_STATUS,''),
                        COALESCE(TRIM(STATE_CD),''), COALESCE(LEFT(REGEXP_REPLACE(ZIP_CD,'[^0-9]',''),5),'')), 256),
         UPDATED_TS
  FROM CV_&{ENV}_RAW.PROVIDER.STRM_PROVIDER_STAGE
  WHERE PROVIDER_NPI IS NOT NULL AND REGEXP_LIKE(TRIM(PROVIDER_NPI), '[0-9]{10}')
  QUALIFY ROW_NUMBER() OVER (PARTITION BY TRIM(PROVIDER_NPI) ORDER BY UPDATED_TS DESC, _FILE_ROW DESC) = 1;

  MERGE INTO CV_&{ENV}_CORE.PROVIDER.DIM_PROVIDER t
  USING (
      SELECT s.PROVIDER_NPI AS MERGE_KEY, s.* FROM TMP_PROVIDER_SRC s
      UNION ALL
      SELECT NULL, s.* FROM TMP_PROVIDER_SRC s
      JOIN CV_&{ENV}_CORE.PROVIDER.DIM_PROVIDER d
        ON d.PROVIDER_NPI = s.PROVIDER_NPI AND d.IS_CURRENT AND NOT d.IS_INFERRED AND d.ROW_HASH <> s.ROW_HASH
  ) s
  ON t.PROVIDER_NPI = s.MERGE_KEY AND t.IS_CURRENT
  WHEN MATCHED AND t.IS_INFERRED THEN UPDATE SET
       PROVIDER_NAME = s.PROVIDER_NAME, PROVIDER_TYPE = s.PROVIDER_TYPE, SPECIALTY_CD = s.SPECIALTY_CD,
       TAXONOMY_CD = s.TAXONOMY_CD, NETWORK_ID = s.NETWORK_ID, IS_PARTICIPATING = s.IS_PARTICIPATING,
       STATE_CD = s.STATE_CD, ZIP5 = s.ZIP5, ROW_HASH = s.ROW_HASH, IS_INFERRED = FALSE,
       _BATCH_ID = :P_BATCH_ID, _UPDATED_AT = CURRENT_TIMESTAMP()
  WHEN MATCHED AND t.ROW_HASH <> s.ROW_HASH THEN UPDATE SET
       EFFECTIVE_TO = s.SOURCE_UPDATED_TS, IS_CURRENT = FALSE, _BATCH_ID = :P_BATCH_ID, _UPDATED_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT
       (PROVIDER_SK, PROVIDER_NPI, PROVIDER_NAME, PROVIDER_TYPE, SPECIALTY_CD, TAXONOMY_CD, NETWORK_ID, IS_PARTICIPATING,
        STATE_CD, ZIP5, IS_INFERRED, ROW_HASH, EFFECTIVE_FROM, EFFECTIVE_TO, IS_CURRENT, _BATCH_ID)
       VALUES (CV_&{ENV}_CORE.COMMON.SEQ_PROVIDER_SK.NEXTVAL, s.PROVIDER_NPI, s.PROVIDER_NAME, s.PROVIDER_TYPE, s.SPECIALTY_CD,
               s.TAXONOMY_CD, s.NETWORK_ID, s.IS_PARTICIPATING, s.STATE_CD, s.ZIP5, FALSE, s.ROW_HASH,
               s.SOURCE_UPDATED_TS, '9999-12-31'::TIMESTAMP_NTZ, TRUE, :P_BATCH_ID);
  SELECT "number of rows inserted", "number of rows updated" INTO :v_ins, :v_upd FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));
  COMMIT;

  CALL CV_&{ENV}_CONTROL.AUDIT.SP_LOG_BATCH(:P_BATCH_ID, 'SP_MERGE_DIM_PROVIDER', 'CV_&{ENV}_CORE.PROVIDER.DIM_PROVIDER',
                                            'SUCCESS', :v_ins, :v_upd, 0, NULL);
  RETURN OBJECT_CONSTRUCT('inserted_versions', v_ins, 'expired_or_upgraded', v_upd);
EXCEPTION
  WHEN OTHER THEN
    ROLLBACK;
    CALL CV_&{ENV}_CONTROL.AUDIT.SP_LOG_BATCH(:P_BATCH_ID, 'SP_MERGE_DIM_PROVIDER', 'CV_&{ENV}_CORE.PROVIDER.DIM_PROVIDER',
                                              'FAILED', 0, 0, 0, :SQLERRM);
    RAISE;
END;
$$;
