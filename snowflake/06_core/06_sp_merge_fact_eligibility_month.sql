/* =============================================================================
   06_sp_merge_fact_eligibility_month.sql — explode eligibility spans to months
   Replaces m_ELG_MBR_MONTHS (Normalizer over a month calendar + Aggregator).
   Member-month rule ELG-R-001: eligible on the 15th of the month.
   Recompute affected members only (members whose spans changed in this batch).
   ============================================================================= */
USE ROLE &{ENV}_SR_CICD;

CREATE OR REPLACE PROCEDURE CV_&{ENV}_CONTROL.ORCHESTRATION.SP_MERGE_FACT_ELIGIBILITY_MONTH(P_BATCH_ID VARCHAR)
RETURNS VARIANT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  v_members NUMBER DEFAULT 0;
  v_rows    NUMBER DEFAULT 0;
BEGIN
  CREATE OR REPLACE TEMPORARY TABLE TMP_ELIG_MEMBERS (MEMBER_ID VARCHAR(20));
  CREATE OR REPLACE TEMPORARY TABLE TMP_ELIG_SPANS LIKE CV_&{ENV}_STAGE.MEMBERSHIP.ELIGIBILITY_SPAN;

  BEGIN TRANSACTION;
  INSERT INTO TMP_ELIG_SPANS
  SELECT * EXCLUDE (METADATA$ACTION, METADATA$ISUPDATE, METADATA$ROW_ID)
  FROM CV_&{ENV}_STAGE.MEMBERSHIP.STRM_STG_ELIG_CORE;

  -- current span state per member lives in CORE.MEMBER.ELIGIBILITY_SPAN_CURRENT
  MERGE INTO CV_&{ENV}_CORE.MEMBER.ELIGIBILITY_SPAN_CURRENT t
  USING (SELECT * FROM TMP_ELIG_SPANS
         QUALIFY ROW_NUMBER() OVER (PARTITION BY ELIG_SPAN_ID ORDER BY SOURCE_UPDATED_TS DESC) = 1) s
  ON t.ELIG_SPAN_ID = s.ELIG_SPAN_ID
  WHEN MATCHED THEN UPDATE SET MEMBER_ID = s.MEMBER_ID, PLAN_ID = s.PLAN_ID, LOB_CODE = s.LOB_CODE,
       EFFECTIVE_DT = s.EFFECTIVE_DT, TERM_DT = s.TERM_DT, COVERAGE_TIER = s.COVERAGE_TIER, IS_VOID = s.IS_VOID,
       SOURCE_UPDATED_TS = s.SOURCE_UPDATED_TS
  WHEN NOT MATCHED THEN INSERT VALUES (s.ELIG_SPAN_ID, s.MEMBER_ID, s.PLAN_ID, s.LOB_CODE, s.EFFECTIVE_DT, s.TERM_DT,
       s.COVERAGE_TIER, s.IS_VOID, s.SOURCE_UPDATED_TS);

  INSERT INTO TMP_ELIG_MEMBERS SELECT DISTINCT MEMBER_ID FROM TMP_ELIG_SPANS;
  v_members := SQLROWCOUNT;

  DELETE FROM CV_&{ENV}_CORE.MEMBER.FACT_ELIGIBILITY_MONTH f
  USING TMP_ELIG_MEMBERS m WHERE f.MEMBER_ID = m.MEMBER_ID;

  INSERT INTO CV_&{ENV}_CORE.MEMBER.FACT_ELIGIBILITY_MONTH
        (MEMBER_SK, MEMBER_ID, PLAN_ID, LOB_CODE, ELIGIBILITY_MONTH, COVERAGE_TIER, MEMBER_MONTH, ELIG_SPAN_ID, _BATCH_ID, _UPDATED_AT)
  SELECT COALESCE(dm.MEMBER_SK, -1), sp.MEMBER_ID, sp.PLAN_ID, sp.LOB_CODE, d.MONTH_START, sp.COVERAGE_TIER,
         IFF(DATEADD(day, 14, d.MONTH_START) BETWEEN sp.EFFECTIVE_DT AND COALESCE(sp.TERM_DT, '9999-12-31'), 1, 0),
         sp.ELIG_SPAN_ID, :P_BATCH_ID, CURRENT_TIMESTAMP()
  FROM CV_&{ENV}_CORE.MEMBER.ELIGIBILITY_SPAN_CURRENT sp
  JOIN TMP_ELIG_MEMBERS m ON m.MEMBER_ID = sp.MEMBER_ID
  JOIN (SELECT DISTINCT MONTH_START FROM CV_&{ENV}_CORE.COMMON.DIM_DATE) d
    ON d.MONTH_START BETWEEN DATE_TRUNC('month', sp.EFFECTIVE_DT)
                         AND DATE_TRUNC('month', LEAST(COALESCE(sp.TERM_DT, CURRENT_DATE()), CURRENT_DATE()))
  LEFT JOIN CV_&{ENV}_CORE.MEMBER.DIM_MEMBER dm ON dm.MEMBER_ID = sp.MEMBER_ID AND dm.IS_CURRENT
  WHERE NOT sp.IS_VOID
  QUALIFY ROW_NUMBER() OVER (PARTITION BY sp.MEMBER_ID, sp.LOB_CODE, d.MONTH_START
                             ORDER BY IFF(DATEADD(day,14,d.MONTH_START) BETWEEN sp.EFFECTIVE_DT AND COALESCE(sp.TERM_DT,'9999-12-31'),1,0) DESC,
                                      sp.EFFECTIVE_DT DESC, sp.ELIG_SPAN_ID DESC) = 1;
  v_rows := SQLROWCOUNT;
  COMMIT;

  CALL CV_&{ENV}_CONTROL.AUDIT.SP_LOG_BATCH(:P_BATCH_ID, 'SP_MERGE_FACT_ELIGIBILITY_MONTH',
       'CV_&{ENV}_CORE.MEMBER.FACT_ELIGIBILITY_MONTH', 'SUCCESS', :v_rows, 0, 0, NULL);
  RETURN OBJECT_CONSTRUCT('members_recomputed', v_members, 'member_month_rows', v_rows);
EXCEPTION
  WHEN OTHER THEN
    ROLLBACK;
    CALL CV_&{ENV}_CONTROL.AUDIT.SP_LOG_BATCH(:P_BATCH_ID, 'SP_MERGE_FACT_ELIGIBILITY_MONTH',
         'CV_&{ENV}_CORE.MEMBER.FACT_ELIGIBILITY_MONTH', 'FAILED', 0, 0, 0, :SQLERRM);
    RAISE;
END;
$$;
