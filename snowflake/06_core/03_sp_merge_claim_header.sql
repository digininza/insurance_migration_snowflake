/* =============================================================================
   03_sp_merge_claim_header.sql — keep CLAIM_HEADER_CURRENT (latest header per claim)
   Runs first in the claims branch of the DAG; line staging joins to it.
   ============================================================================= */
USE ROLE &{ENV}_SR_CICD;

CREATE OR REPLACE PROCEDURE CV_&{ENV}_CONTROL.ORCHESTRATION.SP_MERGE_CLAIM_HEADER(P_BATCH_ID VARCHAR)
RETURNS VARIANT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  v_ins NUMBER DEFAULT 0;
  v_upd NUMBER DEFAULT 0;
BEGIN
  BEGIN TRANSACTION;
  MERGE INTO CV_&{ENV}_CORE.CLAIMS.CLAIM_HEADER_CURRENT t
  USING (
      SELECT TRIM(CLAIM_ID) CLAIM_ID, UPPER(TRIM(CLAIM_TYPE)) CLAIM_TYPE, TRIM(MEMBER_ID) MEMBER_ID,
             TRIM(SUBSCRIBER_ID) SUBSCRIBER_ID, NULLIF(TRIM(BILLING_PROVIDER_NPI),'') BILLING_PROVIDER_NPI,
             RECEIVED_DT, ADJUDICATED_TS, PAID_DT, UPPER(TRIM(CLAIM_STATUS)) CLAIM_STATUS,
             UPPER(TRIM(LOB_CODE)) LOB_CODE, SOURCE_ROWVERSION
      FROM CV_&{ENV}_RAW.CLAIMS.STRM_CLAIM_HEADER_STAGE
      WHERE CLAIM_ID IS NOT NULL
      QUALIFY ROW_NUMBER() OVER (PARTITION BY TRIM(CLAIM_ID) ORDER BY SOURCE_ROWVERSION DESC, _LOAD_TS DESC) = 1
  ) s
  ON t.CLAIM_ID = s.CLAIM_ID
  WHEN MATCHED AND s.SOURCE_ROWVERSION > t.SOURCE_ROWVERSION THEN UPDATE SET
       CLAIM_TYPE = s.CLAIM_TYPE, MEMBER_ID = s.MEMBER_ID, SUBSCRIBER_ID = s.SUBSCRIBER_ID,
       BILLING_PROVIDER_NPI = s.BILLING_PROVIDER_NPI, RECEIVED_DT = s.RECEIVED_DT, ADJUDICATED_TS = s.ADJUDICATED_TS,
       PAID_DT = s.PAID_DT, CLAIM_STATUS = s.CLAIM_STATUS, LOB_CODE = s.LOB_CODE,
       SOURCE_ROWVERSION = s.SOURCE_ROWVERSION, _UPDATED_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT
       (CLAIM_ID, CLAIM_TYPE, MEMBER_ID, SUBSCRIBER_ID, BILLING_PROVIDER_NPI, RECEIVED_DT, ADJUDICATED_TS, PAID_DT,
        CLAIM_STATUS, LOB_CODE, SOURCE_ROWVERSION, _UPDATED_AT)
       VALUES (s.CLAIM_ID, s.CLAIM_TYPE, s.MEMBER_ID, s.SUBSCRIBER_ID, s.BILLING_PROVIDER_NPI, s.RECEIVED_DT,
               s.ADJUDICATED_TS, s.PAID_DT, s.CLAIM_STATUS, s.LOB_CODE, s.SOURCE_ROWVERSION, CURRENT_TIMESTAMP());
  SELECT "number of rows inserted", "number of rows updated" INTO :v_ins, :v_upd FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));
  COMMIT;
  CALL CV_&{ENV}_CONTROL.AUDIT.SP_LOG_BATCH(:P_BATCH_ID, 'SP_MERGE_CLAIM_HEADER', 'CV_&{ENV}_CORE.CLAIMS.CLAIM_HEADER_CURRENT',
                                            'SUCCESS', :v_ins, :v_upd, 0, NULL);
  RETURN OBJECT_CONSTRUCT('inserted', v_ins, 'updated', v_upd);
EXCEPTION
  WHEN OTHER THEN
    ROLLBACK;
    CALL CV_&{ENV}_CONTROL.AUDIT.SP_LOG_BATCH(:P_BATCH_ID, 'SP_MERGE_CLAIM_HEADER', 'CV_&{ENV}_CORE.CLAIMS.CLAIM_HEADER_CURRENT',
                                              'FAILED', 0, 0, 0, :SQLERRM);
    RAISE;
END;
$$;
