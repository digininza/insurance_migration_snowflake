/* =============================================================================
   01_sequences_dims.sql — CORE conformed dimensions (Kimball, SCD2 where needed)
   Surrogate keys from SEQUENCEs (replace Informatica Sequence Generator).
   -1 = unknown member/provider row, inserted once.
   ============================================================================= */
USE ROLE &{ENV}_SR_CICD;

CREATE SEQUENCE IF NOT EXISTS CV_&{ENV}_CORE.COMMON.SEQ_MEMBER_SK   START = 1 INCREMENT = 1 ORDER;
CREATE SEQUENCE IF NOT EXISTS CV_&{ENV}_CORE.COMMON.SEQ_PROVIDER_SK START = 1 INCREMENT = 1 ORDER;
CREATE SEQUENCE IF NOT EXISTS CV_&{ENV}_CORE.COMMON.SEQ_PLAN_SK     START = 1 INCREMENT = 1 ORDER;
CREATE SEQUENCE IF NOT EXISTS CV_&{ENV}_CORE.COMMON.SEQ_GROUP_SK    START = 1 INCREMENT = 1 ORDER;
CREATE SEQUENCE IF NOT EXISTS CV_&{ENV}_CORE.COMMON.SEQ_CLAIM_LINE_SK START = 1 INCREMENT = 1 NOORDER;  -- high volume: NOORDER is faster

-- ------------------------------------------------------------------ DIM_DATE
CREATE TABLE IF NOT EXISTS CV_&{ENV}_CORE.COMMON.DIM_DATE (
    DATE_SK NUMBER(8,0) PRIMARY KEY,       -- YYYYMMDD smart key
    CALENDAR_DATE DATE NOT NULL, MONTH_START DATE, YEAR_NUM NUMBER(4,0), QUARTER_NUM NUMBER(1,0),
    MONTH_NUM NUMBER(2,0), MONTH_NAME VARCHAR(10), DAY_OF_WEEK NUMBER(1,0), IS_WEEKEND BOOLEAN,
    IS_MONTH_END BOOLEAN, FISCAL_YEAR NUMBER(4,0)
) COMMENT = 'Grain: calendar day 2010-01-01 .. 2035-12-31';

INSERT INTO CV_&{ENV}_CORE.COMMON.DIM_DATE
SELECT TO_NUMBER(TO_CHAR(d,'YYYYMMDD')), d, DATE_TRUNC('month', d), YEAR(d), QUARTER(d), MONTH(d),
       MONTHNAME(d), DAYOFWEEKISO(d), DAYOFWEEKISO(d) IN (6,7), d = LAST_DAY(d), YEAR(DATEADD(month, 6, d))
FROM (SELECT DATEADD(day, SEQ4(), '2010-01-01'::DATE) d FROM TABLE(GENERATOR(ROWCOUNT => 9497)))
WHERE NOT EXISTS (SELECT 1 FROM CV_&{ENV}_CORE.COMMON.DIM_DATE);

-- ------------------------------------------------------------------- DIM_LOB
CREATE TABLE IF NOT EXISTS CV_&{ENV}_CORE.COMMON.DIM_LOB (
    LOB_SK NUMBER(4,0) PRIMARY KEY, LOB_CODE VARCHAR(4) UNIQUE, LOB_NAME VARCHAR(40), REGULATOR VARCHAR(40), MLR_TARGET NUMBER(5,4)
);
MERGE INTO CV_&{ENV}_CORE.COMMON.DIM_LOB t
USING (SELECT * FROM VALUES (-1,'UNK','Unknown',NULL,NULL),(1,'COM','Commercial','State DOI',0.8000),
                            (2,'MA','Medicare Advantage','CMS',0.8500),(3,'MCD','Medicaid Managed Care','State Medicaid',0.8500)
       AS s(LOB_SK, LOB_CODE, LOB_NAME, REGULATOR, MLR_TARGET)) s
ON t.LOB_SK = s.LOB_SK
WHEN NOT MATCHED THEN INSERT VALUES (s.LOB_SK, s.LOB_CODE, s.LOB_NAME, s.REGULATOR, s.MLR_TARGET);

-- ---------------------------------------------------------------- DIM_MEMBER (SCD2, PHI)
CREATE TABLE IF NOT EXISTS CV_&{ENV}_CORE.MEMBER.DIM_MEMBER (
    MEMBER_SK        NUMBER(18,0) NOT NULL,
    MEMBER_ID        VARCHAR(20)  NOT NULL,     -- business key (PHI: DIRECT_ID)
    SUBSCRIBER_ID    VARCHAR(20),
    RELATIONSHIP_CD  VARCHAR(2),
    FIRST_NAME       VARCHAR(60),               -- PHI
    LAST_NAME        VARCHAR(60),               -- PHI
    BIRTH_DT         DATE,                      -- PHI (QUASI_ID)
    GENDER_CD        VARCHAR(1),
    SSN              VARCHAR(11),               -- PHI
    ADDRESS_LINE1    VARCHAR(100),              -- PHI
    CITY             VARCHAR(60),
    STATE_CD         VARCHAR(2),
    ZIP5             VARCHAR(5),                -- PHI (QUASI_ID)
    PHONE            VARCHAR(20),               -- PHI
    EMAIL            VARCHAR(120),              -- PHI
    GROUP_ID         VARCHAR(20),
    LOB_CODE         VARCHAR(4),
    PCP_NPI          VARCHAR(10),
    IS_ACTIVE        BOOLEAN,
    IS_INFERRED      BOOLEAN DEFAULT FALSE,     -- late-arriving member placeholder
    ROW_HASH         VARCHAR(64),
    EFFECTIVE_FROM   TIMESTAMP_NTZ NOT NULL,
    EFFECTIVE_TO     TIMESTAMP_NTZ NOT NULL DEFAULT '9999-12-31'::TIMESTAMP_NTZ,
    IS_CURRENT       BOOLEAN NOT NULL DEFAULT TRUE,
    _BATCH_ID        VARCHAR(64),
    _UPDATED_AT      TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DIM_MEMBER PRIMARY KEY (MEMBER_SK)
) COMMENT = 'Grain: member × version (SCD2). One IS_CURRENT row per MEMBER_ID. SK -1 = unknown.';

INSERT INTO CV_&{ENV}_CORE.MEMBER.DIM_MEMBER (MEMBER_SK, MEMBER_ID, LOB_CODE, EFFECTIVE_FROM, IS_ACTIVE, ROW_HASH)
SELECT -1, 'UNKNOWN', 'UNK', '1900-01-01', FALSE, 'UNKNOWN'
WHERE NOT EXISTS (SELECT 1 FROM CV_&{ENV}_CORE.MEMBER.DIM_MEMBER WHERE MEMBER_SK = -1);

-- -------------------------------------------------------------- DIM_PROVIDER (SCD2)
CREATE TABLE IF NOT EXISTS CV_&{ENV}_CORE.PROVIDER.DIM_PROVIDER (
    PROVIDER_SK NUMBER(18,0) NOT NULL PRIMARY KEY, PROVIDER_NPI VARCHAR(10) NOT NULL, PROVIDER_NAME VARCHAR(200),
    PROVIDER_TYPE VARCHAR(4), SPECIALTY_CD VARCHAR(6), TAXONOMY_CD VARCHAR(10), NETWORK_ID VARCHAR(10),
    IS_PARTICIPATING BOOLEAN, STATE_CD VARCHAR(2), ZIP5 VARCHAR(5), IS_INFERRED BOOLEAN DEFAULT FALSE,
    ROW_HASH VARCHAR(64), EFFECTIVE_FROM TIMESTAMP_NTZ NOT NULL,
    EFFECTIVE_TO TIMESTAMP_NTZ NOT NULL DEFAULT '9999-12-31'::TIMESTAMP_NTZ, IS_CURRENT BOOLEAN NOT NULL DEFAULT TRUE,
    _BATCH_ID VARCHAR(64), _UPDATED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
) COMMENT = 'Grain: provider NPI × version (SCD2). SK -1 = unknown.';

INSERT INTO CV_&{ENV}_CORE.PROVIDER.DIM_PROVIDER (PROVIDER_SK, PROVIDER_NPI, PROVIDER_NAME, EFFECTIVE_FROM, ROW_HASH)
SELECT -1, 'UNKNOWN', 'Unknown provider', '1900-01-01', 'UNKNOWN'
WHERE NOT EXISTS (SELECT 1 FROM CV_&{ENV}_CORE.PROVIDER.DIM_PROVIDER WHERE PROVIDER_SK = -1);

