/* =============================================================================
   05_sp_merge_fact_claim_line.sql — versioned claim-line fact
   Replaces the back half of m_CLM_CLAIM_LINE_LOAD:
     LKP_MEMBER_SK / LKP_PROVIDER_SK (unconnected, default -1) + UPD_CLAIM
   Steps (one transaction):
     1. Consume STAGE stream → temp (latest per version key across batches).
     2. Late-arriving members: insert INFERRED DIM_MEMBER rows so facts get a
        real SK instead of -1 (legacy used -1 and never repaired it).
     3. MERGE on (claim_id, line_no, version) — bounded to the batch's
        SERVICE_MONTH range so the 2.4B-row target prunes to a few % (TB_SCALE §4).
     4. Flip IS_CURRENT_VERSION for superseded versions (same pruning).
   Member/provider lookup = CURRENT dim row (legacy parity; ADR-017 note).
   ============================================================================= */
USE ROLE &{ENV}_SR_CICD;

CREATE OR REPLACE PROCEDURE CV_&{ENV}_CONTROL.ORCHESTRATION.SP_MERGE_FACT_CLAIM_LINE(P_BATCH_ID VARCHAR)
RETURNS VARIANT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  v_min_month DATE;
  v_max_month DATE;
  v_inferred  NUMBER DEFAULT 0;
  v_ins       NUMBER DEFAULT 0;
  v_upd       NUMBER DEFAULT 0;
  v_flipped   NUMBER DEFAULT 0;
BEGIN
  CREATE OR REPLACE TEMPORARY TABLE TMP_CLAIM_LINE_SRC LIKE CV_&{ENV}_STAGE.CLAIMS.CLAIM_LINE;

  BEGIN TRANSACTION;

  INSERT INTO TMP_CLAIM_LINE_SRC
  SELECT * EXCLUDE (METADATA$ACTION, METADATA$ISUPDATE, METADATA$ROW_ID)
  FROM CV_&{ENV}_STAGE.CLAIMS.STRM_STG_CLAIM_LINE_CORE
  QUALIFY ROW_NUMBER() OVER (PARTITION BY CLAIM_ID, LINE_NO, CLAIM_LINE_VERSION
                             ORDER BY SOURCE_ROWVERSION DESC, _STAGED_AT DESC) = 1;

  SELECT MIN(SERVICE_MONTH), MAX(SERVICE_MONTH) INTO :v_min_month, :v_max_month FROM TMP_CLAIM_LINE_SRC;
  IF (v_min_month IS NULL) THEN
    COMMIT;   -- empty stream batch
    RETURN OBJECT_CONSTRUCT('status', 'NO_DATA');
  END IF;

  -- (2) inferred members for late-arriving membership
  INSERT INTO CV_&{ENV}_CORE.MEMBER.DIM_MEMBER
        (MEMBER_SK, MEMBER_ID, LOB_CODE, IS_ACTIVE, IS_INFERRED, ROW_HASH, EFFECTIVE_FROM, EFFECTIVE_TO, IS_CURRENT, _BATCH_ID)
  SELECT CV_&{ENV}_CORE.COMMON.SEQ_MEMBER_SK.NEXTVAL, m.MEMBER_ID, m.LOB_CODE, TRUE, TRUE, 'INFERRED',
         '1900-01-01'::TIMESTAMP_NTZ, '9999-12-31'::TIMESTAMP_NTZ, TRUE, :P_BATCH_ID
  FROM (SELECT DISTINCT MEMBER_ID, LOB_CODE FROM TMP_CLAIM_LINE_SRC WHERE MEMBER_ID IS NOT NULL
        QUALIFY ROW_NUMBER() OVER (PARTITION BY MEMBER_ID ORDER BY LOB_CODE) = 1) m
  WHERE NOT EXISTS (SELECT 1 FROM CV_&{ENV}_CORE.MEMBER.DIM_MEMBER d WHERE d.MEMBER_ID = m.MEMBER_ID);
  v_inferred := SQLROWCOUNT;

  -- (3) versioned MERGE, target pruned by SERVICE_MONTH (cluster key)
  MERGE INTO CV_&{ENV}_CORE.CLAIMS.FACT_CLAIM_LINE t
  USING (
      SELECT s.*,
             COALESCE(m.MEMBER_SK, -1)   AS MEMBER_SK,
             COALESCE(rp.PROVIDER_SK, -1) AS RENDERING_PROVIDER_SK,
             COALESCE(bp.PROVIDER_SK, -1) AS BILLING_PROVIDER_SK,
             COALESCE(l.LOB_SK, -1)       AS LOB_SK
      FROM TMP_CLAIM_LINE_SRC s
      LEFT JOIN CV_&{ENV}_CORE.MEMBER.DIM_MEMBER     m  ON m.MEMBER_ID = s.MEMBER_ID AND m.IS_CURRENT
      LEFT JOIN CV_&{ENV}_CORE.PROVIDER.DIM_PROVIDER rp ON rp.PROVIDER_NPI = s.RENDERING_PROVIDER_NPI AND rp.IS_CURRENT
      LEFT JOIN CV_&{ENV}_CORE.PROVIDER.DIM_PROVIDER bp ON bp.PROVIDER_NPI = s.BILLING_PROVIDER_NPI AND bp.IS_CURRENT
      LEFT JOIN CV_&{ENV}_CORE.COMMON.DIM_LOB        l  ON l.LOB_CODE = s.LOB_CODE
  ) s
  ON  t.CLAIM_ID = s.CLAIM_ID AND t.LINE_NO = s.LINE_NO AND t.CLAIM_LINE_VERSION = s.CLAIM_LINE_VERSION
  AND t.SERVICE_MONTH BETWEEN :v_min_month AND :v_max_month          -- partition pruning on target
  WHEN MATCHED AND s.SOURCE_ROWVERSION > t.SOURCE_ROWVERSION THEN UPDATE SET
       ADJUSTMENT_TYPE = s.ADJUSTMENT_TYPE, MEMBER_SK = s.MEMBER_SK, RENDERING_PROVIDER_SK = s.RENDERING_PROVIDER_SK,
       BILLING_PROVIDER_SK = s.BILLING_PROVIDER_SK, LINE_STATUS = s.LINE_STATUS, DENIAL_REASON_CD = s.DENIAL_REASON_CD,
       PAID_DATE_SK = TO_NUMBER(TO_CHAR(s.PAID_DT,'YYYYMMDD')), PAID_MONTH = DATE_TRUNC('month', s.PAID_DT),
       BILLED_AMT = s.BILLED_AMT, ALLOWED_AMT = s.ALLOWED_AMT, PAID_AMT = s.PAID_AMT,
       MEMBER_LIABILITY_AMT = s.MEMBER_LIABILITY_AMT, SOURCE_ROWVERSION = s.SOURCE_ROWVERSION,
       _BATCH_ID = :P_BATCH_ID, _UPDATED_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT
       (CLAIM_LINE_SK, CLAIM_ID, LINE_NO, CLAIM_LINE_VERSION, IS_CURRENT_VERSION, ADJUSTMENT_TYPE, CLAIM_TYPE,
        MEMBER_SK, RENDERING_PROVIDER_SK, BILLING_PROVIDER_SK, LOB_SK, LOB_CODE, PRIMARY_DX_CD, PROCEDURE_CD,
        PLACE_OF_SERVICE_CD, REVENUE_CD, SERVICE_FROM_DATE_SK, SERVICE_MONTH, RECEIVED_DATE_SK, PAID_DATE_SK, PAID_MONTH,
        LINE_STATUS, DENIAL_REASON_CD, IS_AUTO_ADJUDICATED, UNITS, BILLED_AMT, ALLOWED_AMT, PAID_AMT,
        MEMBER_LIABILITY_AMT, SOURCE_ROWVERSION, _BATCH_ID)
       VALUES (CV_&{ENV}_CORE.COMMON.SEQ_CLAIM_LINE_SK.NEXTVAL, s.CLAIM_ID, s.LINE_NO, s.CLAIM_LINE_VERSION, TRUE,
               s.ADJUSTMENT_TYPE, s.CLAIM_TYPE, s.MEMBER_SK, s.RENDERING_PROVIDER_SK, s.BILLING_PROVIDER_SK, s.LOB_SK,
               s.LOB_CODE, s.PRIMARY_DX_CD, s.PROCEDURE_CD, s.PLACE_OF_SERVICE_CD, s.REVENUE_CD,
               TO_NUMBER(TO_CHAR(s.SERVICE_FROM_DT,'YYYYMMDD')), s.SERVICE_MONTH,
               TO_NUMBER(TO_CHAR(s.RECEIVED_DT,'YYYYMMDD')), TO_NUMBER(TO_CHAR(s.PAID_DT,'YYYYMMDD')),
               DATE_TRUNC('month', s.PAID_DT), s.LINE_STATUS, s.DENIAL_REASON_CD, s.IS_AUTO_ADJUDICATED, s.UNITS,
               s.BILLED_AMT, s.ALLOWED_AMT, s.PAID_AMT, s.MEMBER_LIABILITY_AMT, s.SOURCE_ROWVERSION, :P_BATCH_ID);
  SELECT "number of rows inserted", "number of rows updated" INTO :v_ins, :v_upd FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

  -- (4) only the highest version of each line is current
  UPDATE CV_&{ENV}_CORE.CLAIMS.FACT_CLAIM_LINE t
     SET IS_CURRENT_VERSION = FALSE, _UPDATED_AT = CURRENT_TIMESTAMP()
    FROM (SELECT CLAIM_ID, LINE_NO, MAX(CLAIM_LINE_VERSION) AS MAX_VERSION
          FROM TMP_CLAIM_LINE_SRC GROUP BY 1, 2) s
   WHERE t.CLAIM_ID = s.CLAIM_ID AND t.LINE_NO = s.LINE_NO
     AND t.CLAIM_LINE_VERSION < s.MAX_VERSION AND t.IS_CURRENT_VERSION
     AND t.SERVICE_MONTH BETWEEN :v_min_month AND :v_max_month;
  v_flipped := SQLROWCOUNT;

  COMMIT;

  CALL CV_&{ENV}_CONTROL.AUDIT.SP_LOG_BATCH(:P_BATCH_ID, 'SP_MERGE_FACT_CLAIM_LINE', 'CV_&{ENV}_CORE.CLAIMS.FACT_CLAIM_LINE',
                                            'SUCCESS', :v_ins, :v_upd + :v_flipped, 0, NULL);
  RETURN OBJECT_CONSTRUCT('inserted', v_ins, 'updated', v_upd, 'superseded', v_flipped,
                          'inferred_members', v_inferred, 'service_months', ARRAY_CONSTRUCT(v_min_month, v_max_month));
EXCEPTION
  WHEN OTHER THEN
    ROLLBACK;
    CALL CV_&{ENV}_CONTROL.AUDIT.SP_LOG_BATCH(:P_BATCH_ID, 'SP_MERGE_FACT_CLAIM_LINE', 'CV_&{ENV}_CORE.CLAIMS.FACT_CLAIM_LINE',
                                              'FAILED', 0, 0, 0, :SQLERRM);
    RAISE;
END;
$$;
