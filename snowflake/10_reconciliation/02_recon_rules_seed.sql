/* =============================================================================
   02_recon_rules_seed.sql — reconciliation rules (subset shown; PROD had 212)
   NEW_SQL returns GRAIN_KEY, METRIC_VALUE (as VARCHAR). ':BD' = business date.
   Grain keys are built with the SAME format the Oracle extract uses
   ('LOB|CLAIM_TYPE|YYYY-MM') — legacy 1-char LOB codes mapped back via DECODE.
   ============================================================================= */
USE ROLE &{ENV}_SR_CICD;

MERGE INTO CV_&{ENV}_CONTROL.RECON.RECON_RULE t USING (SELECT * FROM VALUES
 ('RC-L1-001','L1','CLAIM_LINE_FACT','ROW_COUNT_BY_LOB_TYPE_MONTH',
  'Claim line versions by LOB × claim type × service month',
  'SELECT DECODE(LOB_CODE,''COM'',''C'',''MA'',''M'',''MCD'',''D'',''U'')||''|''||CLAIM_TYPE||''|''||TO_CHAR(SERVICE_MONTH,''YYYY-MM''), COUNT(*)::VARCHAR
     FROM CV_&{ENV}_CORE.CLAIMS.FACT_CLAIM_LINE WHERE RECEIVED_DATE_SK <= TO_NUMBER(TO_CHAR(:BD,''YYYYMMDD'')) GROUP BY 1',
  0, 'CRITICAL'),
 ('RC-L2-001','L2','CLAIM_LINE_FACT','PAID_AMT_BY_LOB_TYPE_MONTH',
  'Net paid amount (reversals negative) by LOB × claim type × service month',
  'SELECT DECODE(LOB_CODE,''COM'',''C'',''MA'',''M'',''MCD'',''D'',''U'')||''|''||CLAIM_TYPE||''|''||TO_CHAR(SERVICE_MONTH,''YYYY-MM''), TO_VARCHAR(SUM(PAID_AMT))
     FROM CV_&{ENV}_CORE.CLAIMS.FACT_CLAIM_LINE WHERE RECEIVED_DATE_SK <= TO_NUMBER(TO_CHAR(:BD,''YYYYMMDD'')) GROUP BY 1',
  0.00, 'CRITICAL'),
 ('RC-L2-002','L2','CLAIM_LINE_FACT','ALLOWED_AMT_BY_LOB_TYPE_MONTH',
  'Allowed amount by LOB × claim type × service month',
  'SELECT DECODE(LOB_CODE,''COM'',''C'',''MA'',''M'',''MCD'',''D'',''U'')||''|''||CLAIM_TYPE||''|''||TO_CHAR(SERVICE_MONTH,''YYYY-MM''), TO_VARCHAR(SUM(ALLOWED_AMT))
     FROM CV_&{ENV}_CORE.CLAIMS.FACT_CLAIM_LINE WHERE RECEIVED_DATE_SK <= TO_NUMBER(TO_CHAR(:BD,''YYYYMMDD'')) GROUP BY 1',
  0.00, 'CRITICAL'),
 ('RC-L3-001','L3','CLAIM_LINE_FACT','KEY_HASH_RECEIVED_ON_BD',
  'Per claim line version hash of amounts + status for lines received on BD',
  'SELECT CLAIM_ID||''|''||LINE_NO||''|''||CLAIM_LINE_VERSION,
          MD5(CONCAT_WS(''|'', TO_CHAR(BILLED_AMT,''FM999999999999990.00''), TO_CHAR(ALLOWED_AMT,''FM999999999999990.00''),
                        TO_CHAR(PAID_AMT,''FM999999999999990.00''), LINE_STATUS))
     FROM CV_&{ENV}_CORE.CLAIMS.FACT_CLAIM_LINE WHERE RECEIVED_DATE_SK = TO_NUMBER(TO_CHAR(:BD,''YYYYMMDD''))',
  NULL, 'CRITICAL'),
 ('RC-L1-010','L1','MEMBER_DIM','CURRENT_MEMBERS_BY_LOB',
  'Current members by LOB',
  'SELECT DECODE(LOB_CODE,''COM'',''C'',''MA'',''M'',''MCD'',''D'',''U''), COUNT(*)::VARCHAR
     FROM CV_&{ENV}_CORE.MEMBER.DIM_MEMBER WHERE IS_CURRENT AND MEMBER_SK <> -1 AND NOT IS_INFERRED GROUP BY 1',
  0, 'CRITICAL'),
 ('RC-L5-017','L5','CLAIM_LINE_FACT','RULE_CLM_R_017_VIOLATIONS',
  'CLM-R-017 reversal lines must carry non-positive paid amount',
  'SELECT ''ALL'', COUNT(*)::VARCHAR FROM CV_&{ENV}_CORE.CLAIMS.FACT_CLAIM_LINE WHERE ADJUSTMENT_TYPE = ''RV'' AND PAID_AMT > 0',
  0, 'CRITICAL'),
 ('RC-L5-009','L5','MEMBER_DIM','RULE_MBR_R_009_MULTI_CURRENT',
  'MBR-R-009 exactly one current row per member',
  'SELECT ''ALL'', COUNT(*)::VARCHAR FROM (SELECT MEMBER_ID FROM CV_&{ENV}_CORE.MEMBER.DIM_MEMBER WHERE IS_CURRENT GROUP BY 1 HAVING COUNT(*) > 1)',
  0, 'CRITICAL'),
 ('RC-L6-001','L6','AGG_MBR_MONTHS','MEMBER_MONTHS_BY_LOB_MONTH',
  'Member months (finance KPI) by LOB × month',
  'SELECT DECODE(LOB_CODE,''COM'',''C'',''MA'',''M'',''MCD'',''D'',''U'')||''|''||TO_CHAR(ELIGIBILITY_MONTH,''YYYY-MM''), SUM(MEMBER_MONTHS)::VARCHAR
     FROM CV_&{ENV}_MART.FINANCE.DT_MEMBER_MONTHS WHERE ELIGIBILITY_MONTH <= DATE_TRUNC(''month'', :BD) GROUP BY 1',
  0, 'CRITICAL'),
 ('RC-L6-002','L6','PMPM','PAID_PMPM_BY_LOB_MONTH',
  'Paid PMPM by LOB × month (executive KPI)',
  'SELECT DECODE(LOB_CODE,''COM'',''C'',''MA'',''M'',''MCD'',''D'',''U'')||''|''||TO_CHAR(MONTH_START,''YYYY-MM''), TO_VARCHAR(PAID_PMPM)
     FROM CV_&{ENV}_MART.FINANCE.DT_PMPM_BY_LOB_MONTH WHERE MONTH_START <= DATE_TRUNC(''month'', :BD)',
  0.01, 'CRITICAL')
 AS s(RULE_ID, RECON_LEVEL, TABLE_NAME, METRIC_NAME, DESCRIPTION, NEW_SQL, TOLERANCE, CRITICALITY)) s
ON t.RULE_ID = s.RULE_ID
WHEN MATCHED THEN UPDATE SET RECON_LEVEL=s.RECON_LEVEL, TABLE_NAME=s.TABLE_NAME, METRIC_NAME=s.METRIC_NAME,
     DESCRIPTION=s.DESCRIPTION, NEW_SQL=s.NEW_SQL, TOLERANCE=s.TOLERANCE, CRITICALITY=s.CRITICALITY
WHEN NOT MATCHED THEN INSERT (RULE_ID, RECON_LEVEL, TABLE_NAME, METRIC_NAME, DESCRIPTION, NEW_SQL, TOLERANCE, CRITICALITY)
     VALUES (s.RULE_ID, s.RECON_LEVEL, s.TABLE_NAME, s.METRIC_NAME, s.DESCRIPTION, s.NEW_SQL, s.TOLERANCE, s.CRITICALITY);
