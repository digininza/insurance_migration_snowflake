USE ROLE &{ENV}_SR_CICD;
USE SCHEMA CV_&{ENV}_CONTROL.RECON;

CREATE TABLE IF NOT EXISTS RECON_RULE (
    RULE_ID        VARCHAR(20) PRIMARY KEY,
    RECON_LEVEL    VARCHAR(4),       -- L1 counts | L2 amounts | L3 key hash | L4 types | L5 rules | L6 KPIs
    TABLE_NAME     VARCHAR(100),     -- logical legacy table name, e.g. CLAIM_LINE_FACT
    METRIC_NAME    VARCHAR(100),     -- matches LEGACY_METRIC.METRIC_NAME
    DESCRIPTION    VARCHAR(500),
    NEW_SQL        VARCHAR,          -- must return (GRAIN_KEY VARCHAR, METRIC_VALUE VARCHAR); ':BD' = business date
    TOLERANCE      NUMBER(18,4),     -- NULL = exact string equality (hashes)
    CRITICALITY    VARCHAR(10),      -- CRITICAL | WARN
    IS_ACTIVE      BOOLEAN DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS LEGACY_METRIC (
    BUSINESS_DATE DATE, TABLE_NAME VARCHAR(100), METRIC_NAME VARCHAR(100),
    GRAIN_KEY VARCHAR(500), METRIC_VALUE VARCHAR(200), EXTRACTED_AT TIMESTAMP_NTZ,
    _FILE_NAME VARCHAR, _LOAD_TS TIMESTAMP_LTZ
) CLUSTER BY (BUSINESS_DATE)
  COMMENT = 'Legacy EDW aggregates/hashes computed in Oracle and shipped as Parquet';

CREATE TABLE IF NOT EXISTS LEGACY_SCHEMA (
    TABLE_NAME VARCHAR(100), COLUMN_NAME VARCHAR(100), DATA_TYPE VARCHAR(40),
    DATA_PRECISION NUMBER, DATA_SCALE NUMBER, NULLABLE VARCHAR(1)
) COMMENT = 'Oracle ALL_TAB_COLUMNS snapshot of EDW tables. TABLE_NAME stored as the compat-view suffix (CLAIM_FACT ↔ LEGACY_COMPAT.EDW_CLAIM_FACT) for L4 type parity';

CREATE TABLE IF NOT EXISTS RECON_RESULT (
    RUN_ID          VARCHAR(64),
    BUSINESS_DATE   DATE,
    RULE_ID         VARCHAR(20),
    RECON_LEVEL     VARCHAR(4),
    GRAIN_KEY       VARCHAR(500),
    LEGACY_VALUE    VARCHAR(200),
    NEW_VALUE       VARCHAR(200),
    DIFF            NUMBER(38,4),
    STATUS          VARCHAR(20),     -- MATCH | VALUE_MISMATCH | MISSING_IN_NEW | MISSING_IN_LEGACY | TYPE_MISMATCH
    CRITICALITY     VARCHAR(10),
    DISPOSITION     VARCHAR(20),     -- NULL | FIXED | LEGACY_DEFECT | TIMING | OPEN
    DISPOSITION_BY  VARCHAR(100),
    DISPOSITION_NOTE VARCHAR(1000),
    EVALUATED_AT    TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
) CLUSTER BY (BUSINESS_DATE);

CREATE OR REPLACE VIEW V_RECON_SCORECARD AS
SELECT BUSINESS_DATE, RECON_LEVEL, RULE_ID, CRITICALITY,
       COUNT(*)                                    AS GRAINS_COMPARED,
       COUNT_IF(STATUS = 'MATCH')                  AS MATCHED,
       COUNT_IF(STATUS <> 'MATCH')                 AS BREAKS,
       COUNT_IF(STATUS <> 'MATCH' AND COALESCE(DISPOSITION,'OPEN') = 'OPEN') AS OPEN_BREAKS
FROM RECON_RESULT
QUALIFY RUN_ID = FIRST_VALUE(RUN_ID) OVER (PARTITION BY BUSINESS_DATE ORDER BY EVALUATED_AT DESC)
GROUP BY BUSINESS_DATE, RECON_LEVEL, RULE_ID, CRITICALITY, RUN_ID;

-- Cutover exit criterion #1: consecutive business days with zero open critical breaks
CREATE OR REPLACE VIEW V_CUTOVER_GREEN_DAYS AS
WITH d AS (
    SELECT BUSINESS_DATE, SUM(IFF(CRITICALITY = 'CRITICAL', OPEN_BREAKS, 0)) AS CRIT_OPEN
    FROM V_RECON_SCORECARD GROUP BY 1
), g AS (
    SELECT BUSINESS_DATE, CRIT_OPEN,
           SUM(IFF(CRIT_OPEN > 0, 1, 0)) OVER (ORDER BY BUSINESS_DATE DESC ROWS UNBOUNDED PRECEDING) AS RED_SEEN
    FROM d
)
SELECT COUNT(*) AS CONSECUTIVE_GREEN_DAYS, MAX(BUSINESS_DATE) AS AS_OF
FROM g WHERE RED_SEEN = 0;

