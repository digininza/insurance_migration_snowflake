/* =============================================================================
   03_resource_monitors.sql — cost guard-rails. Quotas are illustrative.
   PROD SLA warehouses (TRANSFORM, BI) NOTIFY only — never auto-suspend PROD ELT.
   ============================================================================= */
USE ROLE ACCOUNTADMIN;

CREATE RESOURCE MONITOR IF NOT EXISTS RM_&{ENV}_ACCOUNT_MONTHLY
  WITH CREDIT_QUOTA = 3000 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 75 PERCENT DO NOTIFY ON 90 PERCENT DO NOTIFY ON 100 PERCENT DO NOTIFY;

CREATE RESOURCE MONITOR IF NOT EXISTS RM_&{ENV}_BACKFILL
  WITH CREDIT_QUOTA = 4500 FREQUENCY = NEVER START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 80 PERCENT DO NOTIFY ON 100 PERCENT DO SUSPEND;   -- whole backfill budget

CREATE RESOURCE MONITOR IF NOT EXISTS RM_&{ENV}_ELT
  WITH CREDIT_QUOTA = 900 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 75 PERCENT DO NOTIFY ON 100 PERCENT DO NOTIFY;

CREATE RESOURCE MONITOR IF NOT EXISTS RM_&{ENV}_ADHOC
  WITH CREDIT_QUOTA = 150 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 75 PERCENT DO NOTIFY ON 100 PERCENT DO SUSPEND ON 110 PERCENT DO SUSPEND_IMMEDIATE;

ALTER WAREHOUSE &{ENV}_WH_BACKFILL    SET RESOURCE_MONITOR = RM_&{ENV}_BACKFILL;
ALTER WAREHOUSE &{ENV}_WH_TRANSFORM   SET RESOURCE_MONITOR = RM_&{ENV}_ELT;
ALTER WAREHOUSE &{ENV}_WH_ADHOC       SET RESOURCE_MONITOR = RM_&{ENV}_ADHOC;
ALTER WAREHOUSE &{ENV}_WH_DATASCIENCE SET RESOURCE_MONITOR = RM_&{ENV}_ADHOC;
