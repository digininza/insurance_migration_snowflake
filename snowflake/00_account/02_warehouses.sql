/* =============================================================================
   02_warehouses.sql — workload-isolated compute (ADR-011, COMPUTE_WAREHOUSES.md)
   Pattern: CREATE IF NOT EXISTS (never recreate a running warehouse) + ALTER SET.
   PROD sizes shown; DEV/QA override to XSMALL / 1 cluster via deploy variable
   &{WH_SCALE} = PROD | NONPROD.
   ============================================================================= */
USE ROLE SYSADMIN;

-- Historical backfill: bulk COPY + history MERGE. Temporary XL; set to XSMALL after backfill.
CREATE WAREHOUSE IF NOT EXISTS &{ENV}_WH_BACKFILL
  WAREHOUSE_SIZE = 'XLARGE' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 14400
  COMMENT = 'Backfill COPY INTO: ~128 files in parallel on XL. Scale UP for throughput.';

-- Non-pipe loads (reference files, replays). Snowpipe itself is serverless.
CREATE WAREHOUSE IF NOT EXISTS &{ENV}_WH_INGEST
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 3600
  COMMENT = 'Task-driven COPY for reference data and replay procedures';

-- Task DAG stored procs + Dynamic Table refresh. MERGE into 2.4B-row fact => scale up, not out.
CREATE WAREHOUSE IF NOT EXISTS &{ENV}_WH_TRANSFORM
  WAREHOUSE_SIZE = 'MEDIUM' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 7200 STATEMENT_QUEUED_TIMEOUT_IN_SECONDS = 1800
  COMMENT = 'ELT MERGE/SCD2 + DT refresh. Month-end task resizes to LARGE.';

CREATE WAREHOUSE IF NOT EXISTS &{ENV}_WH_RECON
  WAREHOUSE_SIZE = 'SMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 3600
  COMMENT = 'Legacy vs new reconciliation + DQ; isolated from ETL';

-- BI concurrency: scale OUT (multi-cluster), QAS for outlier scans, longer suspend for cache.
CREATE WAREHOUSE IF NOT EXISTS &{ENV}_WH_BI
  WAREHOUSE_SIZE = 'SMALL' AUTO_SUSPEND = 300 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  MIN_CLUSTER_COUNT = 1 MAX_CLUSTER_COUNT = 4 SCALING_POLICY = 'STANDARD'
  ENABLE_QUERY_ACCELERATION = TRUE QUERY_ACCELERATION_MAX_SCALE_FACTOR = 8
  STATEMENT_TIMEOUT_IN_SECONDS = 900 STATEMENT_QUEUED_TIMEOUT_IN_SECONDS = 120
  COMMENT = 'Power BI + LEGACY_COMPAT consumers';

CREATE WAREHOUSE IF NOT EXISTS &{ENV}_WH_DATASCIENCE
  WAREHOUSE_SIZE = 'MEDIUM' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 3600 COMMENT = 'Actuarial / Snowpark notebooks';

CREATE WAREHOUSE IF NOT EXISTS &{ENV}_WH_ADHOC
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 900 COMMENT = 'Exploration; strict timeout';

CREATE WAREHOUSE IF NOT EXISTS &{ENV}_WH_CICD
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Deployments and tests';

-- Grants
GRANT USAGE, OPERATE ON WAREHOUSE &{ENV}_WH_BACKFILL    TO ROLE &{ENV}_SR_INGEST;
GRANT USAGE, OPERATE ON WAREHOUSE &{ENV}_WH_BACKFILL    TO ROLE &{ENV}_SR_TRANSFORM;
GRANT USAGE, OPERATE ON WAREHOUSE &{ENV}_WH_INGEST      TO ROLE &{ENV}_SR_INGEST;
GRANT USAGE, OPERATE, MODIFY ON WAREHOUSE &{ENV}_WH_TRANSFORM TO ROLE &{ENV}_SR_TRANSFORM;  -- MODIFY: month-end resize task
GRANT USAGE, OPERATE ON WAREHOUSE &{ENV}_WH_RECON       TO ROLE &{ENV}_SR_RECON;
GRANT USAGE          ON WAREHOUSE &{ENV}_WH_BI          TO ROLE &{ENV}_FR_BI_SERVICE;
GRANT USAGE          ON WAREHOUSE &{ENV}_WH_BI          TO ROLE &{ENV}_FR_CLAIMS_OPS;
GRANT USAGE          ON WAREHOUSE &{ENV}_WH_BI          TO ROLE &{ENV}_FR_MEDICAID_ANALYST;
GRANT USAGE          ON WAREHOUSE &{ENV}_WH_BI          TO ROLE &{ENV}_FR_FINANCE;
GRANT USAGE          ON WAREHOUSE &{ENV}_WH_DATASCIENCE TO ROLE &{ENV}_FR_ACTUARY;
GRANT USAGE          ON WAREHOUSE &{ENV}_WH_ADHOC       TO ROLE &{ENV}_FR_DATA_ENGINEER;
GRANT USAGE          ON WAREHOUSE &{ENV}_WH_ADHOC       TO ROLE &{ENV}_FR_PHI_STEWARD;
GRANT USAGE          ON WAREHOUSE &{ENV}_WH_ADHOC       TO ROLE &{ENV}_FR_AUDITOR;
GRANT USAGE, OPERATE ON WAREHOUSE &{ENV}_WH_CICD        TO ROLE &{ENV}_SR_CICD;
GRANT USAGE          ON WAREHOUSE &{ENV}_WH_TRANSFORM   TO ROLE &{ENV}_SR_CICD;   -- DT owner needs the refresh warehouse
GRANT MONITOR ON WAREHOUSE &{ENV}_WH_TRANSFORM TO ROLE &{ENV}_FR_DATA_ENGINEER;
GRANT MONITOR ON WAREHOUSE &{ENV}_WH_BI        TO ROLE &{ENV}_FR_DATA_ENGINEER;
