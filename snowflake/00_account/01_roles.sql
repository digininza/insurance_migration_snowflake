/* =============================================================================
   01_roles.sql — RBAC: access roles (_AR_) hold privileges, functional roles
   (_FR_) are what humans/SCIM groups get, service roles (_SR_) for pipelines.
   Run as SECURITYADMIN.  Variables: &{ENV} = DEV | QA | PROD
   ============================================================================= */
USE ROLE SECURITYADMIN;

-- Service roles (non-human)
CREATE ROLE IF NOT EXISTS &{ENV}_SR_INGEST     COMMENT = 'ADF loader + Snowpipe owner: write RAW';
CREATE ROLE IF NOT EXISTS &{ENV}_SR_TRANSFORM  COMMENT = 'Task DAG / stored procs: RAW read, STAGE/CORE/MART write';
CREATE ROLE IF NOT EXISTS &{ENV}_SR_RECON      COMMENT = 'Reconciliation engine: CORE/MART read, RECON write';
CREATE ROLE IF NOT EXISTS &{ENV}_SR_CICD       COMMENT = 'CI/CD deployer: owns objects in env databases';

-- Functional roles (humans, provisioned by SCIM from Entra ID groups)
CREATE ROLE IF NOT EXISTS &{ENV}_FR_DATA_ENGINEER    COMMENT = 'All layers read, PHI masked';
CREATE ROLE IF NOT EXISTS &{ENV}_FR_ACTUARY          COMMENT = 'CORE + MART read, DOB to year, names masked';
CREATE ROLE IF NOT EXISTS &{ENV}_FR_CLAIMS_OPS       COMMENT = 'MART.CLAIMS read; row access Commercial + Medicare';
CREATE ROLE IF NOT EXISTS &{ENV}_FR_MEDICAID_ANALYST COMMENT = 'MART read; row access Medicaid only';
CREATE ROLE IF NOT EXISTS &{ENV}_FR_FINANCE          COMMENT = 'MART.FINANCE read';
CREATE ROLE IF NOT EXISTS &{ENV}_FR_PHI_STEWARD      COMMENT = 'Unmasked PHI, audited, time-bound membership';
CREATE ROLE IF NOT EXISTS &{ENV}_FR_BI_SERVICE       COMMENT = 'Power BI / Cognos service: MART + LEGACY_COMPAT read';
CREATE ROLE IF NOT EXISTS &{ENV}_FR_AUDITOR          COMMENT = 'CONTROL + ACCOUNT_USAGE read';

-- Access roles per database (read / read-write)
CREATE ROLE IF NOT EXISTS &{ENV}_AR_RAW_R;      CREATE ROLE IF NOT EXISTS &{ENV}_AR_RAW_RW;
CREATE ROLE IF NOT EXISTS &{ENV}_AR_STAGE_R;    CREATE ROLE IF NOT EXISTS &{ENV}_AR_STAGE_RW;
CREATE ROLE IF NOT EXISTS &{ENV}_AR_CORE_R;     CREATE ROLE IF NOT EXISTS &{ENV}_AR_CORE_RW;
CREATE ROLE IF NOT EXISTS &{ENV}_AR_MART_R;     CREATE ROLE IF NOT EXISTS &{ENV}_AR_MART_RW;
CREATE ROLE IF NOT EXISTS &{ENV}_AR_CONTROL_R;  CREATE ROLE IF NOT EXISTS &{ENV}_AR_CONTROL_RW;

-- Hierarchy: RW includes R
GRANT ROLE &{ENV}_AR_RAW_R     TO ROLE &{ENV}_AR_RAW_RW;
GRANT ROLE &{ENV}_AR_STAGE_R   TO ROLE &{ENV}_AR_STAGE_RW;
GRANT ROLE &{ENV}_AR_CORE_R    TO ROLE &{ENV}_AR_CORE_RW;
GRANT ROLE &{ENV}_AR_MART_R    TO ROLE &{ENV}_AR_MART_RW;
GRANT ROLE &{ENV}_AR_CONTROL_R TO ROLE &{ENV}_AR_CONTROL_RW;

-- Service role wiring
GRANT ROLE &{ENV}_AR_RAW_RW     TO ROLE &{ENV}_SR_INGEST;
GRANT ROLE &{ENV}_AR_CONTROL_RW TO ROLE &{ENV}_SR_INGEST;
GRANT ROLE &{ENV}_AR_RAW_R      TO ROLE &{ENV}_SR_TRANSFORM;
GRANT ROLE &{ENV}_AR_STAGE_RW   TO ROLE &{ENV}_SR_TRANSFORM;
GRANT ROLE &{ENV}_AR_CORE_RW    TO ROLE &{ENV}_SR_TRANSFORM;
GRANT ROLE &{ENV}_AR_MART_RW    TO ROLE &{ENV}_SR_TRANSFORM;
GRANT ROLE &{ENV}_AR_CONTROL_RW TO ROLE &{ENV}_SR_TRANSFORM;
GRANT ROLE &{ENV}_AR_CORE_R     TO ROLE &{ENV}_SR_RECON;
GRANT ROLE &{ENV}_AR_MART_R     TO ROLE &{ENV}_SR_RECON;
GRANT ROLE &{ENV}_AR_CONTROL_RW TO ROLE &{ENV}_SR_RECON;

-- Functional role wiring
GRANT ROLE &{ENV}_AR_RAW_R, &{ENV}_AR_STAGE_R, &{ENV}_AR_CORE_R, &{ENV}_AR_MART_R, &{ENV}_AR_CONTROL_R
      TO ROLE &{ENV}_FR_DATA_ENGINEER;
GRANT ROLE &{ENV}_AR_CORE_R, &{ENV}_AR_MART_R TO ROLE &{ENV}_FR_ACTUARY;
GRANT ROLE &{ENV}_AR_MART_R    TO ROLE &{ENV}_FR_CLAIMS_OPS;
GRANT ROLE &{ENV}_AR_MART_R    TO ROLE &{ENV}_FR_MEDICAID_ANALYST;
GRANT ROLE &{ENV}_AR_MART_R    TO ROLE &{ENV}_FR_FINANCE;
GRANT ROLE &{ENV}_AR_MART_R    TO ROLE &{ENV}_FR_BI_SERVICE;
GRANT ROLE &{ENV}_AR_CORE_R    TO ROLE &{ENV}_FR_PHI_STEWARD;
GRANT ROLE &{ENV}_AR_CONTROL_R TO ROLE &{ENV}_FR_AUDITOR;

-- Everything rolls up to SYSADMIN (never orphan roles)
GRANT ROLE &{ENV}_SR_INGEST, &{ENV}_SR_TRANSFORM, &{ENV}_SR_RECON, &{ENV}_SR_CICD TO ROLE SYSADMIN;
GRANT ROLE &{ENV}_FR_DATA_ENGINEER, &{ENV}_FR_ACTUARY, &{ENV}_FR_CLAIMS_OPS, &{ENV}_FR_MEDICAID_ANALYST,
           &{ENV}_FR_FINANCE, &{ENV}_FR_PHI_STEWARD, &{ENV}_FR_BI_SERVICE, &{ENV}_FR_AUDITOR TO ROLE SYSADMIN;

-- Tasks run as the owner role: needs EXECUTE TASK / EXECUTE MANAGED TASK
USE ROLE ACCOUNTADMIN;
GRANT EXECUTE TASK, EXECUTE MANAGED TASK ON ACCOUNT TO ROLE &{ENV}_SR_TRANSFORM;
GRANT EXECUTE ALERT ON ACCOUNT TO ROLE &{ENV}_SR_TRANSFORM;
GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE TO ROLE &{ENV}_FR_AUDITOR;
