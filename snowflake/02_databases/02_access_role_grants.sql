/* =============================================================================
   02_access_role_grants.sql — database/schema/future grants to access roles.
   Managed-access schemas: only schema owner / SECURITYADMIN can grant.
   ============================================================================= */
USE ROLE SECURITYADMIN;

-- Pattern per layer: USAGE on db + all schemas; SELECT on all + future tables/views
-- (future grants make new tables readable without a follow-up ticket).
GRANT USAGE ON DATABASE CV_&{ENV}_RAW TO ROLE &{ENV}_AR_RAW_R;
GRANT USAGE ON ALL SCHEMAS IN DATABASE CV_&{ENV}_RAW TO ROLE &{ENV}_AR_RAW_R;
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE CV_&{ENV}_RAW TO ROLE &{ENV}_AR_RAW_R;
GRANT SELECT ON FUTURE TABLES IN DATABASE CV_&{ENV}_RAW TO ROLE &{ENV}_AR_RAW_R;
GRANT INSERT ON FUTURE TABLES IN DATABASE CV_&{ENV}_RAW TO ROLE &{ENV}_AR_RAW_RW;
GRANT USAGE, READ ON FUTURE STAGES IN SCHEMA CV_&{ENV}_RAW.LANDING TO ROLE &{ENV}_AR_RAW_R;
GRANT USAGE ON FUTURE FILE FORMATS IN SCHEMA CV_&{ENV}_RAW.LANDING TO ROLE &{ENV}_AR_RAW_R;
GRANT CREATE PIPE, CREATE STAGE ON SCHEMA CV_&{ENV}_RAW.LANDING TO ROLE &{ENV}_AR_RAW_RW;

GRANT USAGE ON DATABASE CV_&{ENV}_STAGE TO ROLE &{ENV}_AR_STAGE_R;
GRANT USAGE ON ALL SCHEMAS IN DATABASE CV_&{ENV}_STAGE TO ROLE &{ENV}_AR_STAGE_R;
GRANT SELECT ON FUTURE TABLES IN DATABASE CV_&{ENV}_STAGE TO ROLE &{ENV}_AR_STAGE_R;
GRANT INSERT, UPDATE, DELETE, TRUNCATE ON FUTURE TABLES IN DATABASE CV_&{ENV}_STAGE TO ROLE &{ENV}_AR_STAGE_RW;

GRANT USAGE ON DATABASE CV_&{ENV}_CORE TO ROLE &{ENV}_AR_CORE_R;
GRANT USAGE ON ALL SCHEMAS IN DATABASE CV_&{ENV}_CORE TO ROLE &{ENV}_AR_CORE_R;
GRANT SELECT ON FUTURE TABLES IN DATABASE CV_&{ENV}_CORE TO ROLE &{ENV}_AR_CORE_R;
GRANT SELECT ON FUTURE VIEWS  IN DATABASE CV_&{ENV}_CORE TO ROLE &{ENV}_AR_CORE_R;
GRANT INSERT, UPDATE, DELETE ON FUTURE TABLES IN DATABASE CV_&{ENV}_CORE TO ROLE &{ENV}_AR_CORE_RW;
GRANT USAGE ON FUTURE SEQUENCES IN DATABASE CV_&{ENV}_CORE TO ROLE &{ENV}_AR_CORE_RW;

GRANT USAGE ON DATABASE CV_&{ENV}_MART TO ROLE &{ENV}_AR_MART_R;
GRANT USAGE ON ALL SCHEMAS IN DATABASE CV_&{ENV}_MART TO ROLE &{ENV}_AR_MART_R;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN DATABASE CV_&{ENV}_MART TO ROLE &{ENV}_AR_MART_R;
GRANT SELECT ON FUTURE VIEWS          IN DATABASE CV_&{ENV}_MART TO ROLE &{ENV}_AR_MART_R;
GRANT SELECT ON FUTURE TABLES         IN DATABASE CV_&{ENV}_MART TO ROLE &{ENV}_AR_MART_R;

GRANT USAGE ON DATABASE CV_&{ENV}_CONTROL TO ROLE &{ENV}_AR_CONTROL_R;
GRANT USAGE ON ALL SCHEMAS IN DATABASE CV_&{ENV}_CONTROL TO ROLE &{ENV}_AR_CONTROL_R;
GRANT SELECT ON FUTURE TABLES IN DATABASE CV_&{ENV}_CONTROL TO ROLE &{ENV}_AR_CONTROL_R;
GRANT SELECT ON FUTURE VIEWS  IN DATABASE CV_&{ENV}_CONTROL TO ROLE &{ENV}_AR_CONTROL_R;
GRANT INSERT, UPDATE, DELETE ON FUTURE TABLES IN DATABASE CV_&{ENV}_CONTROL TO ROLE &{ENV}_AR_CONTROL_RW;
GRANT USAGE ON FUTURE PROCEDURES IN DATABASE CV_&{ENV}_CONTROL TO ROLE &{ENV}_AR_CONTROL_RW;

-- Ownership model: SR_CICD owns schemas, tables, procs and Dynamic Tables (deployed by CI);
-- SR_TRANSFORM owns the TASKS (tasks run as their owner) and may create the backfill clone.
GRANT CREATE TASK ON SCHEMA CV_&{ENV}_CONTROL.ORCHESTRATION TO ROLE &{ENV}_SR_TRANSFORM;
GRANT CREATE PROCEDURE ON SCHEMA CV_&{ENV}_CONTROL.ORCHESTRATION TO ROLE &{ENV}_SR_TRANSFORM;
GRANT CREATE TABLE ON SCHEMA CV_&{ENV}_CORE.CLAIMS TO ROLE &{ENV}_SR_TRANSFORM;          -- FACT_CLAIM_LINE_BF clone
GRANT OPERATE, MONITOR ON FUTURE DYNAMIC TABLES IN DATABASE CV_&{ENV}_MART TO ROLE &{ENV}_SR_TRANSFORM;
GRANT CREATE ALERT ON SCHEMA CV_&{ENV}_CONTROL.MONITORING TO ROLE &{ENV}_SR_TRANSFORM;

-- Deployer owns objects (CI/CD creates everything as SR_CICD)
GRANT OWNERSHIP ON DATABASE CV_&{ENV}_RAW     TO ROLE &{ENV}_SR_CICD COPY CURRENT GRANTS;
GRANT OWNERSHIP ON DATABASE CV_&{ENV}_STAGE   TO ROLE &{ENV}_SR_CICD COPY CURRENT GRANTS;
GRANT OWNERSHIP ON DATABASE CV_&{ENV}_CORE    TO ROLE &{ENV}_SR_CICD COPY CURRENT GRANTS;
GRANT OWNERSHIP ON DATABASE CV_&{ENV}_MART    TO ROLE &{ENV}_SR_CICD COPY CURRENT GRANTS;
GRANT OWNERSHIP ON DATABASE CV_&{ENV}_CONTROL TO ROLE &{ENV}_SR_CICD COPY CURRENT GRANTS;
