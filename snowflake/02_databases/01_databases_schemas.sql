/* =============================================================================
   01_databases_schemas.sql — layered databases (HLD §3)
   STAGE is TRANSIENT (rebuilt every run → no Fail-safe storage cost).
   ============================================================================= */
USE ROLE SYSADMIN;

CREATE DATABASE IF NOT EXISTS CV_&{ENV}_RAW  DATA_RETENTION_TIME_IN_DAYS = 1
  COMMENT = 'As-landed data from ADLS Parquet + load metadata. Re-loadable from ADLS.';
CREATE TRANSIENT DATABASE IF NOT EXISTS CV_&{ENV}_STAGE DATA_RETENTION_TIME_IN_DAYS = 1
  COMMENT = 'Typed, deduped, DQ-flagged. Transient (no Fail-safe); 1-day retention because STAGE tables carry streams to CORE.';
CREATE DATABASE IF NOT EXISTS CV_&{ENV}_CORE DATA_RETENTION_TIME_IN_DAYS = 30
  COMMENT = 'Conformed Kimball star (SCD2 dims, versioned facts). 30d Time Travel in PROD.';
CREATE DATABASE IF NOT EXISTS CV_&{ENV}_MART DATA_RETENTION_TIME_IN_DAYS = 1
  COMMENT = 'Subject marts: Dynamic Tables, secure views, LEGACY_COMPAT views';
CREATE DATABASE IF NOT EXISTS CV_&{ENV}_CONTROL DATA_RETENTION_TIME_IN_DAYS = 30
  COMMENT = 'Control, audit, DQ, reconciliation, governance, orchestration';

-- RAW: one schema per source system + LANDING for stages/formats
CREATE SCHEMA IF NOT EXISTS CV_&{ENV}_RAW.LANDING     WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS CV_&{ENV}_RAW.CLAIMS      WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS CV_&{ENV}_RAW.MEMBERSHIP  WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS CV_&{ENV}_RAW.PROVIDER    WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS CV_&{ENV}_RAW.BILLING     WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS CV_&{ENV}_RAW.PHARMACY    WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS CV_&{ENV}_RAW.REFERENCE   WITH MANAGED ACCESS;

CREATE TRANSIENT SCHEMA IF NOT EXISTS CV_&{ENV}_STAGE.CLAIMS      WITH MANAGED ACCESS;
CREATE TRANSIENT SCHEMA IF NOT EXISTS CV_&{ENV}_STAGE.MEMBERSHIP  WITH MANAGED ACCESS;
CREATE TRANSIENT SCHEMA IF NOT EXISTS CV_&{ENV}_STAGE.PROVIDER    WITH MANAGED ACCESS;
CREATE TRANSIENT SCHEMA IF NOT EXISTS CV_&{ENV}_STAGE.BILLING     WITH MANAGED ACCESS;
CREATE TRANSIENT SCHEMA IF NOT EXISTS CV_&{ENV}_STAGE.PHARMACY    WITH MANAGED ACCESS;
CREATE TRANSIENT SCHEMA IF NOT EXISTS CV_&{ENV}_STAGE.QUARANTINE  WITH MANAGED ACCESS;

CREATE SCHEMA IF NOT EXISTS CV_&{ENV}_CORE.COMMON    WITH MANAGED ACCESS;   -- DIM_DATE, DIM_LOB, sequences
CREATE SCHEMA IF NOT EXISTS CV_&{ENV}_CORE.MEMBER    WITH MANAGED ACCESS;   -- DIM_MEMBER, DIM_GROUP, DIM_PLAN, FACT_ELIGIBILITY_MONTH
CREATE SCHEMA IF NOT EXISTS CV_&{ENV}_CORE.PROVIDER  WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS CV_&{ENV}_CORE.CLAIMS    WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS CV_&{ENV}_CORE.FINANCE   WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS CV_&{ENV}_CORE.PHARMACY  WITH MANAGED ACCESS;

CREATE SCHEMA IF NOT EXISTS CV_&{ENV}_MART.CLAIMS        WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS CV_&{ENV}_MART.FINANCE       WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS CV_&{ENV}_MART.PROVIDER      WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS CV_&{ENV}_MART.REGULATORY    WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS CV_&{ENV}_MART.LEGACY_COMPAT WITH MANAGED ACCESS;

CREATE SCHEMA IF NOT EXISTS CV_&{ENV}_CONTROL.CONTROL       WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS CV_&{ENV}_CONTROL.AUDIT         WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS CV_&{ENV}_CONTROL.DQ            WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS CV_&{ENV}_CONTROL.RECON         WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS CV_&{ENV}_CONTROL.GOVERNANCE    WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS CV_&{ENV}_CONTROL.ORCHESTRATION WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS CV_&{ENV}_CONTROL.MONITORING    WITH MANAGED ACCESS;
