/* =============================================================================
   01_raw_tables.sql — RAW = source-shaped, insert-only, + load lineage columns.
   Types are the source types (Parquet logical types), NOT business-cleaned.
   ENABLE_SCHEMA_EVOLUTION: new source columns are added automatically on load
   (RAW only — STAGE/CORE changes go through CI).
   CHANGE_TRACKING is implied by streams; append-only streams are used.
   ============================================================================= */
USE ROLE &{ENV}_SR_CICD;

-- --------------------------------------------------------------------- CLAIMS
CREATE TABLE IF NOT EXISTS CV_&{ENV}_RAW.CLAIMS.CLAIM_HEADER (
    CLAIM_ID               VARCHAR(20),
    CLAIM_TYPE             VARCHAR(2),       -- P professional / I institutional
    MEMBER_ID              VARCHAR(20),
    SUBSCRIBER_ID          VARCHAR(20),
    BILLING_PROVIDER_NPI   VARCHAR(10),
    RECEIVED_DT            DATE,
    ADJUDICATED_TS         TIMESTAMP_NTZ,
    PAID_DT                DATE,
    CLAIM_STATUS           VARCHAR(10),
    LOB_CODE               VARCHAR(4),
    SOURCE_ROWVERSION      NUMBER(20,0),     -- SQL Server rowversion → watermark
    UPDATED_TS             TIMESTAMP_NTZ,
    _FILE_NAME             VARCHAR,
    _FILE_ROW              NUMBER,
    _FILE_LAST_MODIFIED    TIMESTAMP_LTZ,
    _LOAD_TS               TIMESTAMP_LTZ
) ENABLE_SCHEMA_EVOLUTION = TRUE
  COMMENT = 'Grain: one row per claim header version extracted. Source: claims admin SQL Server dbo.CLM_HDR';

CREATE TABLE IF NOT EXISTS CV_&{ENV}_RAW.CLAIMS.CLAIM_LINE (
    CLAIM_ID               VARCHAR(20),
    LINE_NO                NUMBER(4,0),
    CLAIM_LINE_VERSION     NUMBER(4,0),      -- increments on each adjudication/adjustment
    ADJUSTMENT_TYPE        VARCHAR(2),       -- OR original, RV reversal, AD adjustment
    RENDERING_PROVIDER_NPI VARCHAR(10),
    SERVICE_FROM_DT        DATE,
    SERVICE_TO_DT          DATE,
    PROCEDURE_CD           VARCHAR(7),
    PROCEDURE_MODIFIER     VARCHAR(2),
    REVENUE_CD             VARCHAR(4),
    PLACE_OF_SERVICE_CD    VARCHAR(2),
    PRIMARY_DX_CD          VARCHAR(8),
    UNITS                  NUMBER(9,2),
    BILLED_AMT             NUMBER(18,2),
    ALLOWED_AMT            NUMBER(18,2),
    PAID_AMT               NUMBER(18,2),
    COPAY_AMT              NUMBER(18,2),
    COINSURANCE_AMT        NUMBER(18,2),
    DEDUCTIBLE_AMT         NUMBER(18,2),
    LINE_STATUS            VARCHAR(10),      -- PAID / DENIED / PENDED / VOID
    DENIAL_REASON_CD       VARCHAR(10),
    AUTO_ADJUDICATED_FLG   VARCHAR(1),
    SOURCE_ROWVERSION      NUMBER(20,0),
    UPDATED_TS             TIMESTAMP_NTZ,
    _FILE_NAME             VARCHAR,
    _FILE_ROW              NUMBER,
    _FILE_LAST_MODIFIED    TIMESTAMP_LTZ,
    _LOAD_TS               TIMESTAMP_LTZ
) ENABLE_SCHEMA_EVOLUTION = TRUE
  COMMENT = 'Grain: claim line version as extracted. ~9-12M rows/day incremental; ~2.4B history.';

CREATE TABLE IF NOT EXISTS CV_&{ENV}_RAW.CLAIMS.CLAIM_DIAGNOSIS (
    CLAIM_ID VARCHAR(20), DX_SEQ NUMBER(2,0), DX_CD VARCHAR(8), DX_POA_FLG VARCHAR(1),
    UPDATED_TS TIMESTAMP_NTZ,
    _FILE_NAME VARCHAR, _FILE_ROW NUMBER, _FILE_LAST_MODIFIED TIMESTAMP_LTZ, _LOAD_TS TIMESTAMP_LTZ
) ENABLE_SCHEMA_EVOLUTION = TRUE COMMENT = 'Grain: claim × diagnosis sequence (normalized at source)';

