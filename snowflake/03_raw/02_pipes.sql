-- PBM CSV: positional columns → transformation SELECT (no MATCH_BY_COLUMN_NAME for CSV here)
CREATE PIPE IF NOT EXISTS CV_&{ENV}_RAW.LANDING.PIPE_PBM_CLAIM
  AUTO_INGEST = TRUE INTEGRATION = 'NI_CV_&{ENV}_ADLS_EVENTS'
AS COPY INTO CV_&{ENV}_RAW.PHARMACY.PBM_CLAIM
   FROM (SELECT $1,$2,$3,$4,$5,TO_DATE($6,'YYYYMMDD'),$7,$8,$9,$10,$11,$12,$13,
                METADATA$FILENAME, METADATA$FILE_ROW_NUMBER, METADATA$FILE_LAST_MODIFIED, METADATA$START_SCAN_TIME
         FROM @CV_&{ENV}_RAW.LANDING.STG_ADLS_RAW/incremental/pbm/rx_claim/)
   FILE_FORMAT = (FORMAT_NAME = 'CV_&{ENV}_RAW.LANDING.FF_PBM_PIPE')
   ON_ERROR = 'SKIP_FILE';

-- Pipes run as owner; the loader role needs MONITOR/OPERATE for REFRESH and status checks
GRANT MONITOR, OPERATE ON ALL PIPES IN SCHEMA CV_&{ENV}_RAW.LANDING TO ROLE &{ENV}_SR_INGEST;

