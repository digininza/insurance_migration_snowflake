/* =============================================================================
   02_pipes.sql — Snowpipe AUTO_INGEST (incremental path only, ADR-007).
   One pipe per RAW table; each pipe watches a unique path prefix so a single
   BlobCreated event can only match one pipe.
   Parquet: MATCH_BY_COLUMN_NAME + INCLUDE_METADATA (lineage columns) — no
   transformation SELECT, so schema evolution keeps working.
   ============================================================================= */
USE ROLE &{ENV}_SR_CICD;

CREATE PIPE IF NOT EXISTS CV_&{ENV}_RAW.LANDING.PIPE_CLAIM_HEADER
  AUTO_INGEST = TRUE INTEGRATION = 'NI_CV_&{ENV}_ADLS_EVENTS'
  COMMENT = 'raw/incremental/claims/claim_header/**'
AS COPY INTO CV_&{ENV}_RAW.CLAIMS.CLAIM_HEADER
   FROM @CV_&{ENV}_RAW.LANDING.STG_ADLS_RAW/incremental/claims/claim_header/
   FILE_FORMAT = (FORMAT_NAME = 'CV_&{ENV}_RAW.LANDING.FF_PARQUET')
   MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
   INCLUDE_METADATA = (_FILE_NAME = METADATA$FILENAME, _FILE_ROW = METADATA$FILE_ROW_NUMBER,
                       _FILE_LAST_MODIFIED = METADATA$FILE_LAST_MODIFIED, _LOAD_TS = METADATA$START_SCAN_TIME)
   ON_ERROR = 'SKIP_FILE';   -- a corrupt file is skipped whole (visible in COPY_HISTORY) → replay after fix

